"""Phase 7 evidence table: each short-budget arm against the control and the control's seed spread.

    python scripts/rec_ablation_table.py --control runs/GW-REC-003 runs/GW-REC-004 runs/GW-REC-005 \
        --arms runs/GW-REC-006 runs/GW-REC-007 ...

The first control run is the reference each arm is paired with: the arms use its seed. What an arm
changed is read from the configs the runs saved, not typed by hand. Decision rule, fixed before
any arm ran (docs/PHASE_STATUS.md, Phase 07):

- better: the paired 95% CI of the CER difference against the reference lies below zero, and the
  arm's CER is below every control seed's;
- worse: that CI lies above zero, and the arm's CER is above every control seed's;
- otherwise, no clear difference.

The CIs are not corrected for the number of comparisons; the table says how many were made
(EXPERIMENT_PROTOCOL §4). Arms without a finished run are listed as pending. Writes
``reports/training/phase07/ablation_table.md`` and ``.json``.
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path
from typing import Any

from rec_compare import Paired, diff, load, pair_runs, pct

from glypharis.config.loader import config_to_dict, load_config

IGNORED = {"experiment_id", "seed", "checkpoint.dir"}  # differ between runs by design


def flat(d: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    out: dict[str, Any] = {}
    for k, v in d.items():
        out.update(flat(v, f"{prefix}{k}.") if isinstance(v, dict) else {f"{prefix}{k}": v})
    return out


def change(run: Path, reference: Path) -> str:
    """The settings in which a run's saved config differs from the reference's."""
    a, b = (flat(config_to_dict(load_config(r / "config.resolved.yaml"))) for r in (run, reference))
    keys = sorted(k for k in set(a) | set(b) if k not in IGNORED and a.get(k) != b.get(k))
    return ", ".join(f"{k}: {a.get(k)}" for k in keys) or "none"


def verdict(p: Paired, control_cers: list[float]) -> str:
    cer, d = p.cer[0].value, p.d_cer
    if d.high < 0 and cer < min(control_cers):
        return "better"
    if d.low > 0 and cer > max(control_cers):
        return "worse"
    return "no clear difference"


def finished(run: Path) -> bool:
    return (run / "summary.json").exists() and (run / "val_best_samples.jsonl").exists()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--control", type=Path, nargs="+", required=True)
    parser.add_argument("--arms", type=Path, nargs="*", default=[])
    parser.add_argument("--out", type=Path, default=Path("reports/training/phase07"))
    args = parser.parse_args(argv)
    if not all(finished(c) for c in args.control):
        raise SystemExit("every control run must have finished")
    reference = args.control[0]
    controls = [load(c)[0] for c in args.control]
    cers = [s["best"]["val_cer"] for s in controls]
    sd = statistics.stdev(cers) if len(cers) > 1 else 0.0
    spread = {
        "runs": [s["experiment_id"] for s in controls],
        "val_cer": cers,
        "mean": statistics.fmean(cers),
        "sd": sd,
        "min": min(cers),
        "max": max(cers),
    }

    rows, out_rows = [], []
    for arm in args.arms:
        if not finished(arm):
            rows.append(f"| {arm.name} | pending | | | | | | |")
            out_rows.append({"run": arm.name, "status": "pending"})
            continue
        p = pair_runs(arm, reference)
        s, what, v = p.first, change(arm, reference), verdict(p, cers)
        cer = p.cer[0]
        rows.append(f"| {s['experiment_id']} | {what} | {s.get('parameters', 0):,} | "
                    f"{s['steps']:,} | {s['train_seconds'] / 3600:.2f} | {pct(cer.value)} "
                    f"[{pct(cer.low)}, {pct(cer.high)}] | {diff(p.d_cer)} | {v} |")  # fmt: skip
        out_rows.append({"run": s["experiment_id"], "status": "done", "change": what,
                         "parameters": s.get("parameters"), "steps": s["steps"],
                         "train_seconds": s["train_seconds"], "val_cer": vars(cer),
                         "difference": vars(p.d_cer), "verdict": v})  # fmt: skip
    done = [r for r in out_rows if r["status"] == "done"]
    ref = controls[0]
    md = [
        "# Phase 7 evidence table (short budget)",
        "",
        "Generated by `scripts/rec_ablation_table.py`; do not edit by hand.",
        "",
        "## Control and seed spread",
        "",
        "| Run | Seed | Selected epoch | Val CER % |",
        "|---|---|---|---|",
        *[f"| {s['experiment_id']} | {load_config(c / 'config.resolved.yaml').seed} | "
          f"{s['best_epoch']} | {pct(s['best']['val_cer'])} |"
          for s, c in zip(controls, args.control, strict=True)],
        "",
        f"Mean {pct(spread['mean'])}%, standard deviation {100 * spread['sd']:.2f} points, range "
        f"{pct(spread['min'])} to {pct(spread['max'])}%.",
        "",
        f"## Arms against {ref['experiment_id']}",
        "",
        "Difference: arm minus reference, percentage points, 95% bootstrap CI over lines (the same "
        f"resampled lines for both runs). {len(done)} comparisons, no correction for multiplicity. "
        "Verdict rule: better or worse only when the CI excludes zero and the arm's CER lies "
        "outside the control seeds' range in the same direction.",
        "",
        "| Run | Change against the reference | Parameters | Steps | GPU-hours | Val CER % | "
        "Difference | Verdict |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]  # fmt: skip
    args.out.mkdir(parents=True, exist_ok=True)
    result = {"reference": ref["experiment_id"], "control": spread, "arms": out_rows}
    (args.out / "ablation_table.json").write_text(json.dumps(result, indent=1) + "\n",
                                                  encoding="utf-8")  # fmt: skip
    (args.out / "ablation_table.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"{len(done)} arms compared, {len(out_rows) - len(done)} pending")
    return 0


if __name__ == "__main__":
    sys.exit(main())
