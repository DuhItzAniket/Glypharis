"""Phase 10 reports from the end-to-end runs (GW-E2E-001, 002, 003; validation only).

    python scripts/e2e_report.py --config configs/det/gw-det-001.yaml \
        --pipeline runs/GW-E2E-001 --baseline-run runs/GW-E2E-001-p5 --oracle runs/GW-E2E-002 \
        --calibration reports/calibration/GW-E2E-003/calibration.json --out reports/e2e

Reads each run's ``e2e.json``, ``predictions.jsonl`` and ``lines.jsonl`` (`scripts/e2e_eval.py`)
and writes ``GW-E2E-001/report.md`` (the pipeline on all validation pages, and against the
baselines on the 400 Phase 5 pages) and ``GW-E2E-002/report.md`` (the oracle split of page error,
overall and per blur quartile of Phase 9's slice table, plan item 5), each with its JSON. The
pipeline's own lines get ECE at T = 1 and at GW-E2E-003's T, as information (plan item 3).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np
from e2e_eval import read_predictions, score

from glypharis.config.loader import load_config
from glypharis.data.det_dataset import read_gt_pages
from glypharis.data.download import sha256_file
from glypharis.eval.det_slices import load_or_build_slices
from glypharis.eval.page_metrics import PageResult
from glypharis.eval.stats import paired_ratios_diff_ci, ratio_ci
from glypharis.pipeline.calibration import ece


def _iv(d: dict[str, float] | None, pct: bool = True) -> str:
    if d is None:
        return "n/a"
    f = 100 if pct else 1
    return f"{d['value'] * f:.2f} [{d['low'] * f:.2f}, {d['high'] * f:.2f}]"


def _bag(rs: list[PageResult]) -> tuple[np.ndarray, np.ndarray]:
    return (
        np.array([r.bag_errors for r in rs], dtype=np.float64),
        np.array([r.bag_ref_chars for r in rs], dtype=np.float64),
    )


def pipeline_report(pipe: Path, p5: Path, cal: dict[str, Any] | None, out: Path) -> dict[str, Any]:
    allp = json.loads((pipe / "e2e.json").read_text(encoding="utf-8"))
    base = json.loads((p5 / "e2e.json").read_text(encoding="utf-8"))
    md = [
        "# GW-E2E-001: the GLYPHARIS pipeline on HierText validation",
        "",
        "Generated by `scripts/e2e_report.py`; do not edit by hand. Scored by",
        "`glypharis.eval.page_metrics.evaluate_page`, the code that scored the baselines.",
        "Percent, with 95% page-bootstrap CIs. HierText has no reading order, so order-aware page",
        "CER is n/a.",
        f"Detector overrides: `{' '.join(allp['det_overrides'])}`.",
        "",
    ]
    for track in ("strict", "normalised"):
        g = allp["tracks"][track]["glypharis"]
        md += [
            f"## All {allp['n_pages']:,} validation pages ({track} track)",
            "",
            "| Detection P | Detection R | Detection F1 | Bag-of-lines page CER | E2E line F1 |",
            "|---|---|---|---|---|",
            f"| {_iv(g['det_precision'])} | {_iv(g['det_recall'])} | {_iv(g['det_f1'])} | "
            f"{_iv(g['page_cer_bag_of_lines'])} | {_iv(g['e2e_f1'])} |",
            "",
        ]
    for track in ("strict", "normalised"):
        t = base["tracks"][track]
        g = t["glypharis"]
        md += [
            f"## The {base['n_pages']} Phase 5 pages, against the baselines ({track} track)",
            "",
            "Differences are GLYPHARIS minus the baseline, paired by page (lower CER and higher "
            "F1 are better).",
            "",
            "| System | Bag-of-lines page CER | E2E line F1 | CER difference | F1 difference |",
            "|---|---|---|---|---|",
            f"| **GLYPHARIS** | {_iv(g['page_cer_bag_of_lines'])} | {_iv(g['e2e_f1'])} | | |",
        ]
        for exp, b in t["baselines"].items():
            d = b["glypharis_minus_this"]
            md.append(
                f"| {b['name']} ({exp}) | {_iv(b['page_cer_bag_of_lines'])} | "
                f"{_iv(b['e2e_f1'])} | {_iv(d['page_cer_bag_of_lines'])} | "
                f"{_iv(d['e2e_f1'])} |"
            )
        md.append("")
    mob = base["tracks"]["strict"]["baselines"].get("GW-BASE-002")
    ratio = None
    if mob:
        ratio = (
            base["tracks"]["strict"]["glypharis"]["page_cer_bag_of_lines"]["value"]
            / mob["page_cer_bag_of_lines"]["value"]
        )
        md += [
            f"H1's ratio here (information; H1 is judged on GDC in Phase 14): GLYPHARIS page CER "
            f"over PP-OCRv5 mobile's on the Phase 5 pages, strict track: {ratio:.2f}.",
            "",
        ]
    cal_res = None
    if cal is not None:
        rows = [
            json.loads(x)
            for x in (pipe / "lines.jsonl").read_text(encoding="utf-8").splitlines()
            if x.strip()
        ]
        t_fit = str(float(cal["temperature"]))
        y = np.array([r["correct"] for r in rows], dtype=np.float64)
        c1 = np.array([r["confidence"] for r in rows], dtype=np.float64)
        have = all(t_fit in r["conf_at"] for r in rows)
        ct = np.array([r["conf_at"][t_fit] for r in rows]) if have else None
        cal_res = {
            "lines": len(rows),
            "accuracy": float(y.mean()),
            "ece_at_1": ece(c1, y),
            "temperature": cal["temperature"],
            "ece_at_t": ece(ct, y) if ct is not None else None,
        }
        md += [
            "## Confidence of the pipeline's lines",
            "",
            f"{len(rows):,} predicted lines (lines on don't-care text left out); a line is right "
            "when it matches a care line at IoU 0.5 and its text is exactly right on the strict "
            f"track (accuracy {y.mean():.3f}). ECE (15 equal-mass bins) at T = 1: "
            f"{cal_res['ece_at_1']:.4f}; at GW-E2E-003's T = {cal['temperature']:g}: "
            + (f"{cal_res['ece_at_t']:.4f}." if ct is not None else "not recorded.")
            + " Information only: the temperature was fitted on recognizer crops.",
            "",
        ]
    res = {
        "all_pages": allp,
        "phase5_pages": base,
        "h1_ratio_strict": ratio,
        "pipeline_line_calibration": cal_res,
    }
    d = out / "GW-E2E-001"
    d.mkdir(parents=True, exist_ok=True)
    (d / "report.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    (d / "report.json").write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8", newline="\n")
    return res


def oracle_report(args: argparse.Namespace, out: Path) -> dict[str, Any]:
    cfg = load_config(args.config)
    assert cfg.det is not None
    root = Path(cfg.paths.data_root)
    pages_file = root / cfg.det.data.val_pages[0]
    pipe = read_predictions(args.pipeline / "predictions.jsonl")
    orc = read_predictions(args.oracle / "predictions.jsonl")
    ids = sorted(set(pipe) & set(orc))
    gt = read_gt_pages(pages_file, ids)
    rp, ro = score(pipe, gt, ids, "strict"), score(orc, gt, ids, "strict")
    table = load_or_build_slices([gt[d] for d in ids], sha256_file(pages_file), root, 1280)
    attrs = {p.doc_id: p for p in table.pages}

    def split(sel: list[int]) -> dict[str, Any]:
        ep, cp = _bag([rp[i] for i in sel])
        eo, co = _bag([ro[i] for i in sel])
        cer_p, cer_o = ep.sum() / cp.sum(), eo.sum() / co.sum()
        diff = paired_ratios_diff_ci(eo, co, ep, cp, "pages")
        return {
            "pages": len(sel),
            "cer_pipeline": float(cer_p),
            "cer_oracle": float(cer_o),
            "recognition_share": float(cer_o / cer_p) if cer_p else None,
            "oracle_minus_pipeline": {"value": diff.value, "low": diff.low, "high": diff.high},
            "cer_pipeline_ci": _ci(ep, cp),
            "cer_oracle_ci": _ci(eo, co),
        }

    rows = {"all": split(list(range(len(ids))))}
    care = [i for i, d in enumerate(ids) if attrs[d].n_care > 0]
    blur = np.array([attrs[ids[i]].blur_lapvar for i in care])
    edges = np.quantile(blur, [0.25, 0.5, 0.75])
    q = np.searchsorted(edges, blur, side="right")
    for k in range(4):
        rows[f"blur_Q{k + 1}"] = split([care[j] for j in range(len(care)) if q[j] == k])
    h4 = {
        "q4_recognition_share_above_half": rows["blur_Q4"]["recognition_share"] > 0.5,
        "q1_recognition_share_below_half": rows["blur_Q1"]["recognition_share"] < 0.5,
    }
    md = [
        "# GW-E2E-002: oracle analysis on HierText validation",
        "",
        "Generated by `scripts/e2e_report.py`; do not edit by hand. Bag-of-lines page CER (strict "
        "track, percent, 95% page-bootstrap CIs) of the pipeline (GW-E2E-001) and of the oracle "
        "(the ground-truth care lines, cut and read the same way). Recognition's share of page "
        "error = oracle CER / pipeline CER; detection's share is the rest. Blur quartiles: "
        "variance of the Laplacian over the pages with care lines (Q1 blurriest, Q4 sharpest).",
        "",
        "| Pages | n | Pipeline CER | Oracle CER | Oracle − pipeline | Recognition share |",
        "|---|---|---|---|---|---|",
    ]
    for name, r in rows.items():
        md.append(
            f"| {name} | {r['pages']} | {_iv(r['cer_pipeline_ci'])} | "
            f"{_iv(r['cer_oracle_ci'])} | {_iv(r['oracle_minus_pipeline'])} | "
            f"{r['recognition_share']:.2f} |"
        )
    md += [
        "",
        f"H4's Phase 10 reading (exploratory): recognition's share above one half on Q4: "
        f"{'yes' if h4['q4_recognition_share_above_half'] else 'no'}; below one half on Q1: "
        f"{'yes' if h4['q1_recognition_share_below_half'] else 'no'}.",
        "",
    ]
    res = {"rows": rows, "h4": h4, "blur_edges": [float(x) for x in edges]}
    d = out / "GW-E2E-002"
    d.mkdir(parents=True, exist_ok=True)
    (d / "report.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    (d / "report.json").write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8", newline="\n")
    return res


def _ci(num: np.ndarray, den: np.ndarray) -> dict[str, float]:
    iv = ratio_ci(num, den, "pages")
    return {"value": iv.value, "low": iv.low, "high": iv.high}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--pipeline", type=Path, required=True)
    parser.add_argument("--baseline-run", type=Path, required=True)
    parser.add_argument("--oracle", type=Path, required=True)
    parser.add_argument("--calibration", type=Path, default=None)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    cal = json.loads(args.calibration.read_text(encoding="utf-8")) if args.calibration else None
    a = pipeline_report(args.pipeline, args.baseline_run, cal, args.out)
    b = oracle_report(args, args.out)
    print(
        json.dumps(
            {
                "h1_ratio": a["h1_ratio_strict"],
                "line_calibration": a["pipeline_line_calibration"],
                "oracle_all": b["rows"]["all"],
                "h4": b["h4"],
            },
            indent=1,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
