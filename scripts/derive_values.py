"""Compute the numbers the paper derives from reports (Phase 21, plan item 9).

    python scripts/derive_values.py [--check] [--root .]

No report prints a ratio such as "about 3.7 times slower", so a document may state one only through
this script. The formulas live beside the documents, one file each, in
``research/paper/trace/<doc>.json``; the format is in the docstring of `trace_numbers.py`. Every
input is read from a tracked report under an experiment ID that the report supports, and the result
goes to ``reports/paper_trace/derived.json`` with its formula, inputs, source lines and hashes.

How precise a result may be printed follows from its inputs: a sum or difference keeps the last
digit of its coarsest input, a product or quotient the significant digits of its least precise
input, and literal numbers in a formula are exact. `trace_numbers.py` refuses a number printed more
finely than that.

This module also holds what both checkers need: the experiment registry, the link between an
experiment ID and a report, and the reader of the trace files. It uses the standard library only and
reads only ``reports/``, ``research/``, ``docs/``, ``configs/`` and ``data/manifests/``.

Nothing is written when a formula or an input fails. With ``--check`` nothing is written at all and
the file on disk must equal the computed one after turning CRLF into LF. Exit status 0 on success, 1
otherwise.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from decimal import Context, Decimal
from fractions import Fraction
from pathlib import Path, PurePosixPath
from typing import Any, Final

import numtrace as nt

REGISTRY: Final = "research/experiments.md"
TRACE_DIR: Final = "research/paper/trace"
PAPER_DIR: Final = "research/paper"
ROOT_DOCUMENTS: Final = ("MODEL_CARD.md", "DATASETS.md")
OUTPUT_DIR: Final = "reports/paper_trace"
DERIVED_OUTPUT: Final = f"{OUTPUT_DIR}/derived.json"

# Where a measured number may come from. A path under the last two stands in for an experiment ID.
EVIDENCE_ROOTS: Final = ("reports/", "data/manifests/", "configs/")
STAND_IN_ROOTS: Final = ("data/manifests/", "configs/")
# Hand-written or generated from the documents themselves, so never a source for them.
NOT_EVIDENCE: Final = (
    f"{OUTPUT_DIR}/",
    "research/findings.md",
    "research/research_log.md",
    f"{PAPER_DIR}/",
)

# Reports that name their experiments nowhere the checks below can read them.
REPORT_IDS: Final[dict[str, tuple[str, ...]]] = {
    "reports/benchmark_results/efficiency_comparison.json": (
        "GW-EFF-006",
        "GW-EFF-007",
        "GW-EFF-008",
        "GW-EFF-009",
        "GW-EFF-010",
        "GW-EFF-011",
    ),
}

# Reports that add up many experiments. A total that belongs to none of them, such as a phase's
# hours, may cite the file itself, but only from a bound row that names no experiment: the rows for
# single experiments keep their IDs.
AGGREGATE_REPORTS: Final = frozenset({"reports/compute/ledger.md"})

_ID_RANGE: Final = re.compile(
    r"GW-([A-Z0-9]+)-([0-9]{3})[ \t]*(?:to|–)[ \t]*(?:GW-\1-)?([0-9]{3})(?![0-9])"
)
_GENERATED_BY: Final = re.compile(r"Generated by\b.*")
_REPORT_PATH: Final = re.compile(r"(?:reports|data/manifests)/[\w./-]*[\w/]")
_RUN_FIELDS: Final = ("experiment", "experiment_id", "run", "experiments")
_SIG_DIGITS: Final = 12


class TraceFileError(ValueError):
    """A trace file that does not follow the format."""


@dataclass(frozen=True)
class Problem:
    """Something that fails the check. ``line`` is 0 when no document line applies."""

    document: str
    line: int
    message: str

    def __str__(self) -> str:
        where = f"{self.document}:{self.line}" if self.line else self.document
        return f"{where}: {self.message}"


@dataclass(frozen=True)
class Registered:
    """One row of the experiment registry."""

    experiment: str
    status: str
    reports: tuple[str, ...]

    @property
    def done(self) -> bool:
        return self.status == "done" or self.status.startswith("done ")


def expand_ids(text: str) -> list[str]:
    """The experiment IDs in a text, with ``GW-EFF-006 to 011`` read as the whole range."""
    found = nt.EXPERIMENT_ID.findall(text)
    for match in _ID_RANGE.finditer(text):
        first, last = int(match[2]), int(match[3])
        found.extend(f"GW-{match[1]}-{n:03d}" for n in range(first, last + 1))
    return sorted(set(found))


def read_registry(root: Path) -> dict[str, Registered]:
    """Every experiment in ``research/experiments.md``, from its table."""
    full = root / REGISTRY
    if not full.is_file():
        raise nt.TraceError(f"{REGISTRY}: no such file")
    document = nt.parse_document(full.read_bytes().decode("utf-8"), REGISTRY)
    table = next(
        (t for t in document.tables if {"ID", "Status", "Report"}.issubset(t.header)), None
    )
    if table is None:
        raise nt.TraceError(f"{REGISTRY}: no table with ID, Status and Report columns")
    id_at, status_at, report_at = (table.header.index(n) for n in ("ID", "Status", "Report"))
    registry: dict[str, Registered] = {}
    for row in table.rows:
        found = nt.EXPERIMENT_ID.search(row.cells[id_at])
        if found:
            reports = tuple(_REPORT_PATH.findall(row.cells[report_at]))
            registry[found[0]] = Registered(found[0], row.cells[status_at].strip(), reports)
    return registry


class Repo:
    """The sources of one repository checkout: report index, registry and ID links."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        self.index = nt.ReportIndex(self.root)
        self.registry = read_registry(self.root)
        self._lines: dict[str, list[str]] = {}
        self._claimed: dict[str, dict[str, str]] = {}

    def is_evidence(self, path: str) -> bool:
        return path.startswith(EVIDENCE_ROOTS) and not path.startswith(NOT_EVIDENCE)

    def exists(self, path: str) -> bool:
        try:
            nt.check_source_path(path)
        except nt.SourcePathError:
            return False
        return (self.root / path).is_file()

    def lines(self, path: str) -> list[str]:
        """The lines of a source file, after the checks `ReportIndex` makes."""
        if path not in self._lines:
            self.index.file(path)
            text = (self.root / path).read_bytes().decode("utf-8")
            self._lines[path] = text.replace("\r\n", "\n").split("\n")
        return self._lines[path]

    def folder_files(self, folder: str) -> list[str]:
        """The source files directly in a folder, by name."""
        prefix = folder.rstrip("/") + "/"
        try:
            nt.check_source_path(prefix + "x.md")
        except nt.SourcePathError:
            return []
        base = self.root / folder
        if not base.is_dir():
            return []
        names = sorted(p.name for p in base.iterdir() if p.is_file())
        return [prefix + n for n in names if PurePosixPath(n).suffix in nt.SOURCE_SUFFIXES]

    def registered_files(self, experiment: str) -> list[str]:
        """The files the registry's Report cell names for an experiment."""
        entry = self.registry.get(experiment)
        files: list[str] = []
        for report in entry.reports if entry else ():
            if (self.root / report).is_dir():
                files.extend(self.folder_files(report))
            elif self.exists(report):
                files.append(report)
        return [f for f in files if self.is_evidence(f)]

    def _own_ids(self, path: str) -> list[str]:
        """IDs in a report's ``Generated by`` line or JSON run field."""
        lines = self.lines(path)
        if path.endswith(".md"):
            found = _GENERATED_BY.search("\n".join(lines[:5]))
            return expand_ids(found[0]) if found else []
        if not path.endswith(".json"):
            return []
        data = json.loads("\n".join(lines))
        names: list[str] = []
        for key in _RUN_FIELDS if isinstance(data, dict) else ():
            field = data.get(key)
            if isinstance(field, dict):
                names.extend(str(k) for k in field)
            elif isinstance(field, str):
                names.append(field)
        return expand_ids(" ".join(names))

    def claimed(self, path: str) -> dict[str, str]:
        """Experiment IDs a report belongs to, each with how that is known."""
        if path not in self._claimed:
            kind = "run field" if path.endswith(".json") else "header"
            found = dict.fromkeys(self._own_ids(path), kind)
            for name in nt.EXPERIMENT_ID.findall(path):
                found.setdefault(name, "path")
            for name in REPORT_IDS.get(path, ()):
                found.setdefault(name, "map")
            for entry in self.registry.values():
                for report in entry.reports:
                    folder = report.rstrip("/") + "/"
                    if path == report or path.startswith(folder):
                        found.setdefault(entry.experiment, "registry")
            self._claimed[path] = found
        return self._claimed[path]

    def id_problem(self, experiment: str) -> str | None:
        """Why an ID may not be cited, or None when it is registered as done."""
        entry = self.registry.get(experiment)
        if entry is None:
            return f"{experiment} is not in {REGISTRY}"
        if not entry.done:
            return f"{experiment} is registered as {entry.status!r}, not done"
        return None

    def stand_in_problem(self, path: str, lines: Sequence[int] = ()) -> str | None:
        """Why a path may not stand in for an experiment ID, or None when it may.

        ``lines`` are the source lines a bound row selected, which `AGGREGATE_REPORTS` require.
        """
        if not self.is_evidence(path):
            return f"{path} cannot stand in for an experiment ID"
        if path.startswith(STAND_IN_ROOTS):
            return None
        if path in AGGREGATE_REPORTS:
            if not lines:
                return f"{path} stands in for an experiment ID only in rows bound by trace-table"
            text = self.lines(path)
            for number in lines:
                if nt.EXPERIMENT_ID.search(text[number - 1]):
                    return f"{path}:{number} names an experiment: cite its ID"
            return None
        indexed = self.index.file(path)
        if self.claimed(path) or indexed.ids:
            return f"{path} comes from experiments: cite one of them, not the path"
        return None

    def link(
        self,
        experiment: str,
        path: str,
        anchor: str | None = None,
        lines: Sequence[int] = (),
    ) -> str | None:
        """How an ID is tied to a report, or None when it is not.

        The report claims the ID (`claimed`), or the ID is written where the number was taken from:
        on the given lines, else in the anchored section, else anywhere in the file.
        """
        how = self.claimed(path).get(experiment)
        if how:
            return how
        indexed = self.index.file(path)
        if lines and indexed.kind in ("md", "csv"):
            text = self.lines(path)
            where = "row"
            selected = [text[n - 1] for n in lines if 0 < n <= len(text)]
            return where if any(experiment in line for line in selected) else None
        if anchor and indexed.kind == "md":
            first, last = nt.section_lines(indexed.headings, anchor, indexed.line_count, path)
            section = self.lines(path)[first - 1 : last]
            return "section" if any(experiment in line for line in section) else None
        return "mention" if experiment in indexed.ids else None

    def source_problem(
        self,
        experiment: str,
        path: str,
        anchor: str | None = None,
        lines: Sequence[int] = (),
    ) -> str | None:
        """Why a number may not be attributed to this ID in this file, or None."""
        if not self.is_evidence(path):
            return f"{path} is not a report, manifest or configuration"
        if experiment == path:
            return self.stand_in_problem(path, lines)
        problem = self.id_problem(experiment)
        if problem:
            return problem
        if self.link(experiment, path, anchor, lines) is None:
            place = f"#{anchor}" if anchor and not lines else ""
            return f"{experiment} does not match {path}{place}: not in its header or run field"
        return None


@dataclass(frozen=True)
class Constant:
    """A protocol constant a document may state where ``context`` is found near it."""

    raw: str
    value: Decimal
    unit: str
    context: re.Pattern[str]
    experiment: str
    path: str
    line: int
    sha256: str


@dataclass(frozen=True)
class Published:
    """A figure published by a dataset's authors (``DATASETS.md`` only)."""

    raw: str
    value: Decimal
    unit: str
    context: re.Pattern[str]
    citation: str


@dataclass(frozen=True)
class DerivedInput:
    name: str
    experiment: str
    path: str
    line: int
    raw: str
    value: Fraction
    exponent: int
    sha256: str


@dataclass(frozen=True)
class DerivedValue:
    """A computed value. Its last printable digit is worth 10**``exponent``."""

    document: str
    name: str
    formula: str
    value: Fraction
    exponent: int
    inputs: tuple[DerivedInput, ...]
    note: str = ""

    @property
    def experiments(self) -> tuple[str, ...]:
        return tuple(dict.fromkeys(i.experiment for i in self.inputs))


@dataclass(frozen=True)
class TraceFile:
    document: str
    constants: tuple[Constant, ...] = ()
    published: tuple[Published, ...] = ()
    derived: tuple[DerivedValue, ...] = ()


def document_paths(root: Path) -> list[str]:
    """The documents under the trace rule that exist, in a fixed order."""
    paper = sorted(p.name for p in (root / PAPER_DIR).glob("*.md") if p.is_file())
    found = [f"{PAPER_DIR}/{name}" for name in paper]
    found += [name for name in ROOT_DOCUMENTS if (root / name).is_file()]
    return found


def trace_file_path(document: str) -> str:
    return f"{TRACE_DIR}/{PurePosixPath(document).stem}.json"


def _keys(entry: Any, what: str, required: set[str], optional: set[str]) -> dict[str, Any]:
    if not isinstance(entry, dict):
        raise TraceFileError(f"{what}: expected an object")
    missing = sorted(required - entry.keys())
    unknown = sorted(entry.keys() - required - optional)
    if missing:
        raise TraceFileError(f"{what}: missing {', '.join(missing)}")
    if unknown:
        raise TraceFileError(f"{what}: unknown field {', '.join(unknown)}")
    return entry


def _text(entry: dict[str, Any], key: str, what: str, default: str | None = None) -> str:
    value = entry.get(key, default)
    if not isinstance(value, str) or not value.strip():
        raise TraceFileError(f"{what}: {key} must be a non-empty string")
    return value


def _number(text: str, what: str) -> nt.NumberToken:
    tokens = nt.tokenize(text)
    if len(tokens) != 1:
        raise TraceFileError(f"{what}: {text!r} is not one number")
    return tokens[0]


def _context(entry: dict[str, Any], what: str) -> re.Pattern[str]:
    text = _text(entry, "context", what)
    try:
        return re.compile(text, re.I)
    except re.error as error:
        raise TraceFileError(f"{what}: context is not a valid pattern: {error}") from error


def split_source(source: str, what: str) -> tuple[str, str | None]:
    """``path#anchor`` as a checked path and its anchor."""
    path, mark, anchor = source.partition("#")
    if mark and not anchor:
        raise TraceFileError(f"{what}: empty anchor in {source!r}")
    try:
        nt.check_source_path(path)
    except nt.SourcePathError as error:
        raise TraceFileError(f"{what}: {error}") from error
    return path, anchor or None


def _read_constant(repo: Repo, entry: Any, what: str) -> Constant:
    fields = _keys(entry, what, {"value", "context", "source"}, {"id", "note"})
    raw = _text(fields, "value", what)
    token = _number(raw, what)
    path, anchor = split_source(_text(fields, "source", what), what)
    if path.startswith(NOT_EVIDENCE):
        raise TraceFileError(f"{what}: {path} cannot be the source of a constant")
    experiment = _text(fields, "id", what, path)
    if experiment != path:
        problem = repo.source_problem(experiment, path, anchor)
        if problem:
            raise TraceFileError(f"{what}: {problem}")
    indexed = repo.index.file(path)
    wanted = Fraction(token.value)
    hit = next((v for v in indexed.values_in(anchor) if Fraction(v.value) == wanted), None)
    if hit is None:
        raise TraceFileError(f"{what}: {raw} is not in {_text(fields, 'source', what)}")
    context = _context(fields, what)
    return Constant(
        raw, token.value, token.unit, context, experiment, path, hit.line, indexed.sha256
    )


def _read_published(entry: Any, what: str) -> Published:
    fields = _keys(entry, what, {"value", "context", "citation"}, {"note"})
    raw = _text(fields, "value", what)
    token = _number(raw, what)
    citation = _text(fields, "citation", what)
    return Published(raw, token.value, token.unit, _context(fields, what), citation)


def _row_terms(value: Any, what: str) -> tuple[str, ...]:
    terms = [value] if isinstance(value, str) else value
    if not isinstance(terms, list) or not terms:
        raise TraceFileError(f"{what}: row must be a string or a list of strings")
    if not all(isinstance(t, str) and t.strip() for t in terms):
        raise TraceFileError(f"{what}: row must be a string or a list of strings")
    return tuple(t.strip() for t in terms)


def _read_input(repo: Repo, name: str, entry: Any, what: str) -> DerivedInput:
    fields = _keys(entry, what, {"id", "source"}, {"row", "header", "value"})
    experiment = _text(fields, "id", what)
    path, anchor = split_source(_text(fields, "source", what), what)
    if not repo.is_evidence(path):
        raise TraceFileError(f"{what}: {path} is not a report, manifest or configuration")
    indexed = repo.index.file(path)
    wanted = _number(_text(fields, "value", what), what) if "value" in fields else None
    if "row" in fields:
        terms = _row_terms(fields["row"], what)
        header = _text(fields, "header", what) if "header" in fields else None
        binding = nt.Binding(("input",), terms, header)
        values = list(repo.index.binding_values(path, anchor, binding))
    elif "header" in fields:
        raise TraceFileError(f"{what}: header needs row")
    elif wanted is None:
        raise TraceFileError(f"{what}: give row, value or both")
    else:
        values = list(indexed.values_in(anchor))
    if wanted is not None:
        values = [v for v in values if Fraction(v.value) == Fraction(wanted.value)]
    if not values:
        raise TraceFileError(f"{what}: the selection finds no number in {path}")
    if "row" in fields and len({Fraction(v.value) for v in values}) > 1:
        raise TraceFileError(f"{what}: the selection finds {len(values)} numbers; add value")
    chosen = values[0]
    lines = [chosen.line] if "row" in fields else ()
    problem = repo.source_problem(experiment, path, anchor, lines)
    if problem:
        raise TraceFileError(f"{what}: {problem}")
    return DerivedInput(
        name,
        experiment,
        path,
        chosen.line,
        chosen.raw + chosen.unit,
        Fraction(chosen.value),
        chosen.exponent,
        indexed.sha256,
    )


@dataclass(frozen=True)
class _Quantity:
    """A value and the last digit it can be trusted to; None for an exact literal."""

    value: Fraction
    exponent: int | None


def magnitude(value: Fraction) -> int:
    """The power of ten of a value's leading digit."""
    size = abs(value)
    guess = len(str(size.numerator)) - len(str(size.denominator))
    while Fraction(10) ** guess > size:
        guess -= 1
    while Fraction(10) ** (guess + 1) <= size:
        guess += 1
    return guess


def _digits(quantity: _Quantity) -> int | None:
    if quantity.exponent is None:
        return None
    if quantity.value == 0:
        return 1
    return max(magnitude(quantity.value) - quantity.exponent + 1, 1)


def _added(left: _Quantity, right: _Quantity, value: Fraction) -> _Quantity:
    known = [q.exponent for q in (left, right) if q.exponent is not None]
    return _Quantity(value, max(known) if known else None)


def _multiplied(left: _Quantity, right: _Quantity, value: Fraction) -> _Quantity:
    known = [d for d in (_digits(left), _digits(right)) if d is not None]
    if not known:
        return _Quantity(value, None)
    if value == 0:
        exponents = [q.exponent for q in (left, right) if q.exponent is not None]
        return _Quantity(value, max(exponents))
    return _Quantity(value, magnitude(value) - min(known) + 1)


_FUNCTIONS: Final[dict[str, Callable[..., Fraction]]] = {"abs": abs, "max": max, "min": min}


def _evaluate(node: ast.AST, inputs: dict[str, _Quantity]) -> _Quantity:
    if isinstance(node, ast.Expression):
        return _evaluate(node.body, inputs)
    if isinstance(node, ast.Constant) and type(node.value) in (int, float):
        return _Quantity(Fraction(Decimal(str(node.value))), None)
    if isinstance(node, ast.Name):
        if node.id not in inputs:
            raise TraceFileError(f"unknown input {node.id!r}")
        return inputs[node.id]
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        inner = _evaluate(node.operand, inputs)
        return _Quantity(-inner.value, inner.exponent)
    if isinstance(node, ast.BinOp):
        left, right = _evaluate(node.left, inputs), _evaluate(node.right, inputs)
        if isinstance(node.op, ast.Add):
            return _added(left, right, left.value + right.value)
        if isinstance(node.op, ast.Sub):
            return _added(left, right, left.value - right.value)
        if isinstance(node.op, ast.Mult):
            return _multiplied(left, right, left.value * right.value)
        if isinstance(node.op, ast.Div):
            if right.value == 0:
                raise TraceFileError("division by zero")
            return _multiplied(left, right, left.value / right.value)
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and not node.keywords:
        function = _FUNCTIONS.get(node.func.id)
        if function is not None and node.args:
            arguments = [_evaluate(a, inputs) for a in node.args]
            result = function(*(a.value for a in arguments))
            chosen = next(a for a in arguments if abs(a.value) == abs(result))
            return _Quantity(result, chosen.exponent)
    raise TraceFileError(f"unsupported expression: {type(node).__name__}")


def evaluate_formula(formula: str, inputs: Sequence[DerivedInput]) -> tuple[Fraction, int]:
    """The exact value of a formula and the last digit its inputs support."""
    try:
        tree = ast.parse(formula, mode="eval")
    except SyntaxError as error:
        raise TraceFileError(f"formula {formula!r} does not parse") from error
    used = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)} - _FUNCTIONS.keys()
    names = {i.name for i in inputs}
    if used != names:
        difference = sorted(used ^ names)
        raise TraceFileError(f"formula and inputs disagree on {', '.join(difference)}")
    known = {i.name: _Quantity(i.value, i.exponent) for i in inputs}
    result = _evaluate(tree, known)
    if result.exponent is None:
        raise TraceFileError("the formula uses no input")
    return result.value, result.exponent


def _read_derived(repo: Repo, document: str, entry: Any, what: str) -> DerivedValue:
    fields = _keys(entry, what, {"name", "formula", "inputs"}, {"note"})
    name = _text(fields, "name", what)
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", name):
        raise TraceFileError(f"{what}: {name!r} is not a valid name")
    inputs = fields["inputs"]
    if not isinstance(inputs, dict) or not inputs:
        raise TraceFileError(f"{what}: inputs must be a non-empty object")
    read = tuple(
        _read_input(repo, key, inputs[key], f"{what}, input {key}") for key in sorted(inputs)
    )
    formula = _text(fields, "formula", what)
    try:
        value, exponent = evaluate_formula(formula, read)
    except TraceFileError as error:
        raise TraceFileError(f"{what}: {error}") from error
    note = str(fields.get("note", ""))
    return DerivedValue(document, name, formula, value, exponent, read, note)


def load_trace_file(repo: Repo, document: str) -> tuple[TraceFile, list[Problem]]:
    """Read a document's trace file; a document without one has an empty `TraceFile`.

    Each bad entry becomes a `Problem` and is left out, so one run reports all of them.
    """
    path = trace_file_path(document)
    full = repo.root / path
    if not full.is_file():
        return TraceFile(document), []
    problems: list[Problem] = []

    def problem(message: str) -> None:
        problems.append(Problem(path, 0, message))

    try:
        data = json.loads(full.read_bytes().decode("utf-8"))
        fields = _keys(data, path, {"document"}, {"constants", "published", "derived"})
    except (ValueError, TraceFileError) as error:
        problem(str(error))
        return TraceFile(document), problems
    if fields["document"] != document:
        problem(f"document is {fields['document']!r}, expected {document!r}")
    if fields.get("published") and document != "DATASETS.md":
        problem("published figures are for DATASETS.md only")

    def read_all(key: str, reader: Callable[[Any, str], Any]) -> list[Any]:
        entries = fields.get(key, [])
        if not isinstance(entries, list):
            problem(f"{key} must be a list")
            return []
        kept: list[Any] = []
        for number, entry in enumerate(entries):
            try:
                kept.append(reader(entry, f"{key}[{number}]"))
            except (nt.TraceError, TraceFileError) as error:
                problem(str(error))
        return kept

    constants = read_all("constants", lambda e, w: _read_constant(repo, e, w))
    published = read_all("published", _read_published)
    derived = read_all("derived", lambda e, w: _read_derived(repo, document, e, w))
    names = [d.name for d in derived]
    for name in sorted({n for n in names if names.count(n) > 1}):
        problem(f"derived value {name!r} is declared twice")
    return TraceFile(document, tuple(constants), tuple(published), tuple(derived)), problems


def stray_trace_files(root: Path, documents: Sequence[str]) -> list[Problem]:
    """Trace files whose document does not exist."""
    expected = {trace_file_path(d) for d in documents}
    folder = root / TRACE_DIR
    found = sorted(p.name for p in folder.glob("*.json")) if folder.is_dir() else []
    return [
        Problem(f"{TRACE_DIR}/{name}", 0, "no document of this name")
        for name in found
        if f"{TRACE_DIR}/{name}" not in expected
    ]


def decimal_text(value: Fraction, digits: int = _SIG_DIGITS) -> str:
    """A value to ``digits`` significant digits, without an exponent."""
    context = Context(prec=digits)
    number = context.divide(Decimal(value.numerator), Decimal(value.denominator))
    return format(number, "f")


def render_derived(files: Sequence[TraceFile]) -> str:
    """The text of ``derived.json``."""
    documents: dict[str, Any] = {}
    for trace in sorted(files, key=lambda f: f.document):
        if not trace.derived:
            continue
        entries: dict[str, Any] = {}
        for item in sorted(trace.derived, key=lambda d: d.name):
            entries[item.name] = {
                "formula": item.formula,
                "value": decimal_text(item.value),
                "finest_digit": f"1e{item.exponent}",
                "experiments": list(item.experiments),
                "inputs": {
                    i.name: {
                        "id": i.experiment,
                        "source": i.path,
                        "line": i.line,
                        "value": i.raw,
                        "sha256": i.sha256,
                    }
                    for i in item.inputs
                },
            }
            if item.note:
                entries[item.name]["note"] = item.note
        documents[trace.document] = entries
    body = {"generated_by": "scripts/derive_values.py", "documents": documents}
    return json.dumps(body, indent=2, ensure_ascii=False) + "\n"


def entry_line(rendered: str, document: str, name: str) -> int:
    """The line of a value's entry in the text of ``derived.json``."""
    start = rendered.index(f'    "{document}": {{')
    return rendered.count("\n", 0, rendered.index(f'      "{name}": {{', start)) + 1


def text_sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def write_text(path: Path, text: str) -> None:
    """Write UTF-8 with LF line ends, replacing the file in one step."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(text.encode("utf-8"))
    os.replace(temporary, path)


def is_current(path: Path, text: str) -> bool:
    """True when a file holds ``text``, ignoring CRLF."""
    if not path.is_file():
        return False
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n") == text


def load_all(repo: Repo, documents: Sequence[str]) -> tuple[list[TraceFile], list[Problem]]:
    files: list[TraceFile] = []
    problems = stray_trace_files(repo.root, documents)
    for document in documents:
        trace, found = load_trace_file(repo, document)
        files.append(trace)
        problems.extend(found)
    return files, problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compute the paper's derived values.")
    parser.add_argument("--check", action="store_true", help="compare with the file; write nothing")
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args(argv)
    try:
        repo = Repo(args.root)
    except nt.TraceError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    files, problems = load_all(repo, document_paths(repo.root))
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        return 1
    text = render_derived(files)
    target = repo.root / DERIVED_OUTPUT
    if args.check:
        if not is_current(target, text):
            print(f"error: {DERIVED_OUTPUT} is out of date", file=sys.stderr)
            return 1
        print(f"{DERIVED_OUTPUT} is current")
        return 0
    write_text(target, text)
    count = sum(len(f.derived) for f in files)
    print(f"wrote {DERIVED_OUTPUT}: {count} values")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
