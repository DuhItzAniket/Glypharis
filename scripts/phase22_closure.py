"""The closure checks of Phase 22 (item 21): v1's records after every pass of the phase.

    PYTHONPATH='.;scripts' $PY scripts/phase22_closure.py \
        --odb-before $ROOTS/odb_before_a.txt --odb-before $ROOTS/odb_before_b.txt

Five checks, each reported as passed or failed, never stopped half way:

1. ``v1_files``: every file under the three v1 stores (`phase22_v1_compare.V1_STORES`) against
   reports/final_validation/v1_files_before.json, by SHA-256 and size; nothing missing, changed or
   added.
2. ``omnidocbench_result``: the file names in the OmniDocBench evaluator's own ``result/`` folder,
   now, against each list taken before a pass of the phase (``--odb-before``, one name per line).
   The names are the evaluator's own; the lists hold nothing else.
3. ``phase14_outputs``: every entry of data/manifests/processed/phase14_outputs.json against its
   file, through `phase14_score.check_outputs` (hash, line count, and the run metadata's hash
   where one is recorded).
4. ``access_log``: the log as committed at `START` (the tag of the phase before) is an exact byte
   prefix of the log at HEAD, and the working copy equals HEAD's. The rows added since are counted
   by phase and reason.
5. ``protected_paths``: ``git diff --exit-code START HEAD`` is empty under `PROTECTED`, the paths
   and pinned scripts named in docs/PHASE_STATUS.md, Phase 22 ("How v1's records stay untouched"
   and the Fixed rules).

Writes reports/final_validation/closure.json and closure.md: hashes, counts, IDs and repository
paths only, never a line of text. Exits 1 when any check failed.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import phase14_score as ps
import phase22_v1_compare as cmp

START = "phase-21"
ACCESS_LOG = "research/test_access_log.md"
ODB_RESULT = Path("raw/evaluators/omnidocbench-7ddb8df/result")
OUT = Path("reports/final_validation/closure.json")
PROTECTED = (
    "reports/external",
    "data/manifests/processed/phase14_outputs.json",
    "data/manifests/processed/phase5_baseline_files.json",
    "configs",
    "glypharis/eval",
    "glypharis/pipeline",
    "glypharis/models",
    "glypharis/export",
    "glypharis/data",
    "scripts/ext_eval.py",
    "scripts/phase14_*.py",
    "scripts/evaluate_baselines.py",
    "scripts/official_*.py",
    "scripts/hiertext_eval_launch.py",
    "scripts/run_baselines.py",
)
NOTE = (
    "Generated by scripts/phase22_closure.py; do not edit by hand. Hashes, counts and paths only."
)


def _git(*args: str, raw: bool = False) -> Any:
    done = subprocess.run(["git", *args], capture_output=True, check=False)
    if raw:
        return done
    if done.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {done.stderr.decode(errors='replace')}")
    return done.stdout


# ------------------------------------------------------------------------------------ checks


def compare_files(before: dict[str, Any], now: dict[str, Any]) -> dict[str, Any]:
    missing = sorted(set(before) - set(now))
    added = sorted(set(now) - set(before))
    changed = sorted(k for k in set(before) & set(now) if before[k] != now[k])
    return {
        "before": len(before),
        "now": len(now),
        "missing": missing,
        "added": added,
        "changed": changed,
        "passed": not (missing or added or changed),
    }


def check_v1_files(data: Path, before_path: Path) -> dict[str, Any]:
    before = json.loads(before_path.read_text(encoding="utf-8"))["files"]
    result = compare_files(before, cmp.v1_file_list(data))
    return {"reference": before_path.as_posix(), **result}


def read_names(path: Path) -> list[str]:
    return sorted(n.strip() for n in path.read_text(encoding="utf-8").splitlines() if n.strip())


def check_result_folder(folder: Path, lists: list[Path]) -> dict[str, Any]:
    now = sorted(p.name for p in folder.iterdir()) if folder.is_dir() else None
    befores = [read_names(p) for p in lists]
    passed = now is not None and bool(befores) and all(b == now for b in befores)
    return {
        "folder": "data/" + ODB_RESULT.as_posix(),
        "lists_before": len(befores),
        "files_now": None if now is None else len(now),
        "names_now": now,
        "each_list_equal": [b == now for b in befores],
        "passed": passed,
    }


def check_phase14_outputs(data: Path) -> dict[str, Any]:
    manifest = data / ps.OUTPUTS
    entries = ps._read_outputs(data)["outputs"] if manifest.is_file() else []
    missing = []
    present = []
    for e in entries:
        path = data / ps._norm_file(str(e["file"]))
        if path.is_file():
            present.append(ps.file_entry(path, data))
        else:
            missing.append(ps._norm_file(str(e["file"])))
    try:
        unrecorded = ps.check_outputs(data, present)
        problem = None
    except SystemExit as exc:
        unrecorded, problem = [], str(exc)
    metas = sum(1 for e in entries if e.get("meta_sha256") is not None)
    return {
        "manifest": "data/" + ps.OUTPUTS.as_posix(),
        "entries": len(entries),
        "meta_hashes": metas,
        "checked": len(present),
        "missing": missing,
        "unrecorded": len(unrecorded),
        "problem": problem,
        "passed": bool(entries) and not missing and not unrecorded and problem is None,
    }


def log_rows(text: str) -> list[list[str]]:
    rows = []
    for line in text.splitlines():
        if not line.startswith("| ") or line.startswith("| Date ") or line.startswith("|---"):
            continue
        rows.append([c.strip() for c in line.strip().strip("|").split("|")])
    return rows


def check_access_log(start: bytes, head: bytes, work: bytes) -> dict[str, Any]:
    prefix = head.startswith(start)
    added = log_rows(head[len(start) :].decode("utf-8")) if prefix else []
    by_reason = Counter((r[4], r[5]) for r in added if len(r) == 6)
    return {
        "start": START,
        "start_bytes": len(start),
        "head_bytes": len(head),
        "prefix": prefix,
        "working_copy_equals_head": work == head,
        "rows_at_start": len(log_rows(start.decode("utf-8"))),
        "rows_added": len(added),
        "rows_added_resumed": sum(1 for r in added if "(resumed" in r[-1]),
        "rows_added_by_phase_and_reason": [
            {"phase": ph, "reason": why, "rows": n} for (ph, why), n in sorted(by_reason.items())
        ],
        "passed": prefix and work == head,
    }


def check_protected(start: str) -> dict[str, Any]:
    done = _git("diff", "--exit-code", "--stat", start, "HEAD", "--", *PROTECTED, raw=True)
    changed = _git("diff", "--name-only", start, "HEAD", "--", *PROTECTED).decode().split()
    return {
        "start": start,
        "paths": list(PROTECTED),
        "exit_code": done.returncode,
        "changed_files": changed,
        "passed": done.returncode == 0 and not changed,
    }


# ------------------------------------------------------------------------------------ report


def render(doc: dict[str, Any]) -> str:
    c = doc["checks"]
    v1, odb, p14, log, prot = (
        c["v1_files"],
        c["omnidocbench_result"],
        c["phase14_outputs"],
        c["access_log"],
        c["protected_paths"],
    )
    word = {True: "passed", False: "FAILED"}
    rows = [
        (
            "v1 stores against `v1_files_before.json`",
            f"{v1['now']:,} of {v1['before']:,} files; missing {len(v1['missing'])}, "
            f"changed {len(v1['changed'])}, added {len(v1['added'])}",
            v1["passed"],
        ),
        (
            "OmniDocBench evaluator's `result/` file names",
            f"{odb['files_now']} files now; equal to {sum(odb['each_list_equal'])} of "
            f"{odb['lists_before']} lists taken before a pass",
            odb["passed"],
        ),
        (
            "Phase 14 outputs against `phase14_outputs.json`",
            f"{p14['checked']:,} of {p14['entries']:,} entries checked, {p14['meta_hashes']} with "
            f"a metadata hash; missing {len(p14['missing'])}",
            p14["passed"],
        ),
        (
            f"Access log at `{log['start']}` an exact prefix of HEAD's",
            f"{log['rows_at_start']} rows at the start, {log['rows_added']} added "
            f"({log['rows_added_resumed']} resumed); working copy equals HEAD: "
            f"{'yes' if log['working_copy_equals_head'] else 'no'}",
            log["passed"],
        ),
        (
            f"`git diff --exit-code {prot['start']} HEAD` under the protected paths",
            f"exit code {prot['exit_code']}, {len(prot['changed_files'])} files changed",
            prot["passed"],
        ),
    ]
    lines = [
        "# Phase 22: closure checks",
        "",
        f"{NOTE} HEAD `{doc['head']}`, {doc['date']}.",
        "",
        f"**All checks: {word[doc['passed']]}.**",
        "",
        "| Check | Result | Verdict |",
        "|---|---|---|",
        *[f"| {a} | {b} | {word[p]} |" for a, b, p in rows],
        "",
        "## Access-log rows added in Phase 22, by phase and reason",
        "",
        "| Phase | Reason | Rows |",
        "|---|---|---|",
        *[
            f"| {r['phase']} | {r['reason']} | {r['rows']} |"
            for r in log["rows_added_by_phase_and_reason"]
        ],
        "",
        "Protected paths: " + ", ".join(f"`{p}`" for p in prot["paths"]) + ".",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--data", type=Path, default=Path("data"))
    parser.add_argument("--odb-before", type=Path, action="append", default=[], required=True)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    head = _git("rev-parse", "HEAD").decode().strip()
    checks = {
        "v1_files": check_v1_files(args.data, cmp.V1_FILES),
        "omnidocbench_result": check_result_folder(args.data / ODB_RESULT, args.odb_before),
        "phase14_outputs": check_phase14_outputs(args.data),
        "access_log": check_access_log(
            _git("show", f"{START}:{ACCESS_LOG}"),
            _git("show", f"HEAD:{ACCESS_LOG}"),
            Path(ACCESS_LOG).read_bytes(),
        ),
        "protected_paths": check_protected(START),
    }
    passed = all(c["passed"] for c in checks.values())
    doc = {
        "note": NOTE,
        "date": datetime.now(UTC).date().isoformat(),
        "head": head,
        "passed": passed,
        "checks": checks,
    }
    cmp._write(args.out, doc)
    args.out.with_suffix(".md").write_text(render(doc), encoding="utf-8", newline="\n")
    print(f"{args.out.as_posix()}: {'passed' if passed else 'FAILED'}")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
