"""Phase 9 choices, applied as registered (docs/PHASE_STATUS.md, Phase 09).

    python scripts/det_choose.py best --sweep runs/phase09/sweep_A.npz
    python scripts/det_choose.py overrides --setting '[0.3, 1, "inverse09", 0.5]'
    python scripts/det_choose.py adopted --pair reports/error_cases/detector/GW-DET-004/pair_B.json
    python scripts/det_choose.py resolution --evals runs/phase09/res_A_*.json \
        --profiles reports/efficiency/det_profile --out reports/error_cases/detector/GW-DET-005

``best`` prints the arg-max of micro F1@0.5 in a sweep file (ties: first in grid order).
``overrides`` prints the ``--set``/``--op`` arguments that make a config use a grid setting, one
per line. ``adopted`` prints arm A's setting if the pair says adopt, else arm B's. ``resolution``
applies plan item 5: eligible long sides from the CPU profiles, then the arg-max of F1@0.5 on half
A among them, written as a table with the choice.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np
from det_profile import eligible


def f1(c: np.ndarray) -> float:
    tp, fp, fn = (float(x) for x in c)
    return 2 * tp / (2 * tp + fp + fn) if tp else 0.0


def best(sweep: Path) -> list[Any]:
    z = np.load(sweep)
    totals = z["counts"].sum(axis=0)
    settings = [json.loads(str(s)) for s in z["settings"]]
    k = max(range(len(settings)), key=lambda i: (f1(totals[i]), -i))
    return list(settings[k])


def overrides(setting: list[Any]) -> list[str]:
    b, a, op, t = setting
    mode = "inverse" if op.startswith("inverse") else "dbnet"
    ratio = int(op.removeprefix(mode)) / 10
    return [
        "--set", f"det.post.bin_thresh={b}",
        "--set", f"det.post.min_component_area={a}",
        "--set", f"det.post.box_thresh={t}",
        "--set", f"det.post.operating_points=[{{name: {op}, unclip_mode: {mode}, "
                 f"unclip_ratio: {ratio}}}]",
        "--op", op,
    ]  # fmt: skip


def resolution(evals: list[Path], profiles: Path, out: Path) -> int:
    rows = []
    for p in evals:
        ev = json.loads(p.read_text(encoding="utf-8"))
        ls = int(ev["long_side"])
        prof_path = profiles / f"GW-EFF-001_ls{ls}.json"
        prof = json.loads(prof_path.read_text(encoding="utf-8")) if prof_path.exists() else None
        h = ev["headline"]
        rows.append({
            "long_side": ls, "f1_50": h["f1_50"]["value"], "precision": h["precision"]["value"],
            "recall": h["recall"]["value"], "pages": ev["pages"],
            "det_ms_mean": prof["mean_ms"] if prof else None,
            "est_page_ms_mean": prof["est_page_mean_ms"] if prof else None,
            "est_page_ms_p95": prof["est_page_p95_ms"] if prof else None,
            "eligible": bool(prof and eligible(prof)),
        })  # fmt: skip
    rows.sort(key=lambda r: r["long_side"])
    ok = [r for r in rows if r["eligible"]]
    big_ok = [r for r in ok if r["long_side"] >= 1280]
    if big_ok:
        choice = max(big_ok, key=lambda r: (r["f1_50"], -r["long_side"]))["long_side"]
        note = "the eligible long side with the highest F1@0.5 on half A"
    else:
        choice = 1280
        note = ("no long side of 1280 or more is eligible, so 1280 stays and the gap goes to "
                "Phases 16 and 17 (plan item 5)")  # fmt: skip
    res = {"rows": rows, "choice": choice, "note": note}
    out.mkdir(parents=True, exist_ok=True)
    (out / "resolution_A.json").write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
    md = [
        "# Input resolution on validation half A (GW-DET-005)",
        "",
        "Generated by `scripts/det_choose.py resolution`; do not edit by hand. F1@0.5 from float",
        "forward passes of GW-DET-001 on half A with GW-DET-004's adopted post-processing; times",
        "from GW-EFF-001 (`reports/efficiency/det_latency.md`). Eligible: estimated page time",
        "within ADR-0011's page target.",
        "",
        "| Long side | Pages | Precision | Recall | F1@0.5 | Det ms mean | Est. page ms mean | "
        "Est. page ms p95 | Eligible |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        fmt = lambda v: "-" if v is None else f"{v:.0f}"  # noqa: E731
        md.append(
            f"| {r['long_side']} | {r['pages']} | {r['precision']:.4f} | {r['recall']:.4f} "
            f"| {r['f1_50']:.4f} | {fmt(r['det_ms_mean'])} | {fmt(r['est_page_ms_mean'])} "
            f"| {fmt(r['est_page_ms_p95'])} | {'yes' if r['eligible'] else 'no'} |"
        )
    md += ["", f"Choice: **{choice}**, {note}. It is adopted only if its paired CI against 1280 on "
           "half B lies above 0 (`pair_B.json`).", ""]  # fmt: skip
    (out / "resolution_A.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    return choice


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("best").add_argument("--sweep", type=Path, required=True)
    sub.add_parser("overrides").add_argument("--setting", required=True)
    sub.add_parser("adopted").add_argument("--pair", type=Path, required=True)
    r = sub.add_parser("resolution")
    r.add_argument("--evals", type=Path, nargs="+", required=True)
    r.add_argument("--profiles", type=Path, required=True)
    r.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    if args.cmd == "best":
        print(json.dumps(best(args.sweep)))
    elif args.cmd == "overrides":
        print("\n".join(overrides(json.loads(args.setting))))
    elif args.cmd == "adopted":
        pair = json.loads(args.pair.read_text(encoding="utf-8"))
        arm = pair["arm_a"] if pair["adopt"] else pair["arm_b"]
        print(arm["setting"] if arm.get("setting") else json.dumps(arm.get("op")))
    else:
        print(resolution(args.evals, args.profiles, args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
