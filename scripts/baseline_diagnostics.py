"""Diagnostics behind three baseline results, from validation predictions only.

    python scripts/baseline_diagnostics.py

Explains numbers in `reports/baselines/recognition.md` without touching a test set:

- **Word gaps** (HierText validation lines): how often a system keeps the spaces between words.
  A recognizer that drops them has a word error rate far above its character error rate.
- **Long lines** (GlyphSynth validation lines): output length against reference length, by
  reference length. A recognizer that fails on long lines writes ever shorter output.
- **Letter case** (HierText validation lines): how often a system writes a line with no lowercase
  letter where the reference has some. Such a system loses on the strict track and not on the
  case-folded normalised track.

Both texts go through the strict-track normalisation first (EXPERIMENT_PROTOCOL §2). Writes
`reports/baselines/diagnostics.md` and `diagnostics.json`.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from run_baselines import EXPERIMENTS, SYSTEM_NAMES

from glypharis.data.text import normalize_eval

SETS = ("hiertext_val", "glyphsynth_val")  # validation only, by construction
BUCKETS = ((0, 30), (30, 50), (50, 70), (70, None))
SHORT = 0.6  # an output under 60% of the reference length counts as cut short


def read(path: Path) -> list[tuple[str, str]]:
    pairs = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            r = json.loads(line)
        except json.JSONDecodeError:  # a cut-off last record from an interrupted run
            continue
        pairs.append((normalize_eval(r["ref"], "strict"), normalize_eval(r["pred"], "strict")))
    return pairs


def word_gaps(pairs: list[tuple[str, str]]) -> dict[str, Any]:
    multi = [(r, p) for r, p in pairs if " " in r]
    kept = sum(" " in p for _, p in multi)
    only_spaces = sum(p != r and p.replace(" ", "") == r.replace(" ", "") for r, p in multi)
    return {"lines": len(pairs), "multi_word": len(multi),
            "keeps_a_space": kept / len(multi) if multi else None,
            "wrong_only_in_spaces": only_spaces}  # fmt: skip


def long_lines(pairs: list[tuple[str, str]]) -> dict[str, Any]:
    rows = []
    for lo, hi in BUCKETS:
        sel = [(r, p) for r, p in pairs if len(r) >= lo and (hi is None or len(r) < hi)]
        ratio = sum(len(p) / len(r) for r, p in sel) / len(sel) if sel else None
        short = sum(len(p) < SHORT * len(r) for r, p in sel)
        rows.append({"from": lo, "to": hi, "lines": len(sel), "length_ratio": ratio,
                     "cut_short": short})  # fmt: skip
    return {"lines": len(pairs), "buckets": rows,
            "cut_short": sum(len(p) < SHORT * len(r) for r, p in pairs if r)}  # fmt: skip


def letter_case(pairs: list[tuple[str, str]]) -> dict[str, Any]:
    mixed = [(r, p) for r, p in pairs if any(c.islower() for c in r)]
    upper = sum(not any(c.islower() for c in p) and any(c.isalpha() for c in p) for _, p in mixed)
    return {"lines_with_lowercase": len(mixed), "no_lowercase_output": upper / len(mixed)}


def fmt(v: float | None, pct: bool = False) -> str:
    if v is None:
        return "n/a"
    return f"{100 * v:.1f}" if pct else f"{v:.2f}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-root", default="data")
    parser.add_argument("--out", default="reports/baselines")
    args = parser.parse_args(argv)
    root = Path(args.data_root) / "processed" / "baselines"
    res: dict[str, Any] = {"word_gaps": {}, "long_lines": {}, "letter_case": {}}
    for system, exp in EXPERIMENTS.items():
        hv, gs = (root / exp / f"{system}_rec_{s}.jsonl" for s in SETS)
        if hv.exists():
            pairs = read(hv)
            res["word_gaps"][system] = word_gaps(pairs)
            res["letter_case"][system] = letter_case(pairs)
        if gs.exists():
            res["long_lines"][system] = long_lines(read(gs))

    def name(s: str) -> str:
        return f"{EXPERIMENTS[s]} | {SYSTEM_NAMES[s]}"

    md = [
        "# Baselines: diagnostics",
        "",
        "Generated by `scripts/baseline_diagnostics.py`; do not edit by hand. Validation",
        "predictions only (recognition, ground-truth line crops), both texts in the strict-track",
        "normalisation. They explain results in [recognition.md](recognition.md).",
        "",
        "## Word gaps (HierText validation)",
        "",
        "Lines whose reference has more than one word; the share of predictions with at least one",
        "space, and the lines whose only errors are spaces.",
        "",
        "| ID | System | Multi-word lines | Output keeps a space % | Wrong only in spaces |",
        "|---|---|---|---|---|",
        *[f"| {name(s)} | {r['multi_word']:,} | {fmt(r['keeps_a_space'], True)} | "
          f"{r['wrong_only_in_spaces']:,} |" for s, r in res["word_gaps"].items()],
        "",
        "## Long lines (GlyphSynth validation)",
        "",
        "Mean output length over reference length, by reference length in characters, and the",
        f"outputs under {SHORT:.0%} of the reference length (cut short).",
        "",
        "| ID | System | " + " | ".join(
            f"{lo}-{hi - 1} chars" if hi else f"{lo}+ chars" for lo, hi in BUCKETS
        ) + " | Cut short |",
        "|---|---|" + "---|" * len(BUCKETS) + "---|",
        *[f"| {name(s)} | " + " | ".join(fmt(b["length_ratio"]) for b in r["buckets"])
          + f" | {r['cut_short']:,} of {r['lines']:,} |" for s, r in res["long_lines"].items()],
        "",
        "## Letter case (HierText validation)",
        "",
        "Lines whose reference has a lowercase letter; the share of outputs with letters but none",
        "of them lowercase.",
        "",
        "| ID | System | Lines with lowercase | Output without lowercase % |",
        "|---|---|---|---|",
        *[f"| {name(s)} | {r['lines_with_lowercase']:,} | {fmt(r['no_lowercase_output'], True)} |"
          for s, r in res["letter_case"].items()],
        "",
    ]  # fmt: skip
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "diagnostics.md").write_text("\n".join(md), encoding="utf-8", newline="\n")
    (out / "diagnostics.json").write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8",
                                          newline="\n")  # fmt: skip
    return 0


if __name__ == "__main__":
    sys.exit(main())
