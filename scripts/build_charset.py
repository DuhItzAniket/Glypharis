"""Build the recognizer character set from HierText training labels.

Usage:
    python scripts/build_charset.py [--min-count 10]

Reads legible, non-excluded HierText lines (exclusion list from Phase 3), normalises them with
`normalize_label`, counts characters on the train split, and keeps in-scope characters seen at least
``--min-count`` times. Coverage is measured on train and validation. Writes
``data/manifests/charset.json`` and ``reports/charset/charset_report.md``.
"""

from __future__ import annotations

import argparse
import collections
import sys
import unicodedata
from datetime import UTC, datetime
from pathlib import Path

from glypharis.data.exclusions import Exclusions
from glypharis.data.hiertext import load_split
from glypharis.data.text import (
    NORMALIZATION_RULES,
    NORMALIZATION_VERSION,
    Charset,
    build_charset,
    coverage,
    in_scope,
    normalize_label,
)
from glypharis.utils.gitinfo import git_info

SPLITS = ("train", "validation")


def _label(ch: str) -> str:
    name = unicodedata.name(ch, "?")
    shown = "␠" if ch == " " else ch
    return f"`{shown}` U+{ord(ch):04X} {name.title()}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data-root", default="data")
    parser.add_argument("--reports", default="reports")
    parser.add_argument("--min-count", type=int, default=10)
    args = parser.parse_args(argv)
    root = Path(args.data_root)
    excl = Exclusions.load(root / "manifests" / "exclusions" / "hiertext.json")

    counts: dict[str, collections.Counter[str]] = {}
    stats: dict[str, dict[str, int]] = {}
    lines_text: dict[str, list[str]] = {}
    for split in SPLITS:
        _, anns = load_split(root / "raw" / "hiertext" / "gt" / f"{split}.jsonl.gz")
        c: collections.Counter[str] = collections.Counter()
        st = collections.Counter()
        texts = []
        for ann in anns:
            if excl.image_excluded(split, ann.image_id):
                continue
            for line in ann.lines:
                if not line.legible or excl.line_excluded(split, line.line_id, for_recognizer=True):
                    continue
                label = normalize_label(line.text)
                if not label:
                    st["empty_after_normalisation"] += 1
                    continue
                st["lines"] += 1
                st["changed_by_normalisation"] += label != line.text
                c.update(label)
                texts.append(label)
        counts[split], stats[split], lines_text[split] = c, dict(st), texts

    chars, rare, oos = build_charset(dict(counts["train"]), args.min_count)
    cov = {}
    for split in SPLITS:
        cs_probe = Charset(chars)
        in_scope_counts = {k: v for k, v in counts[split].items() if in_scope(k)}
        lines_ok = sum(1 for t in lines_text[split] if not cs_probe.oov(t))
        cov[split] = {
            "characters_all": coverage(dict(counts[split]), cs_probe),
            "characters_in_scope": coverage(in_scope_counts, cs_probe),
            "lines_fully_covered": lines_ok / max(1, len(lines_text[split])),
        }
    charset = Charset(
        chars,
        version=1,
        metadata={
            "source": "HierText train, legible lines, exclusion list "
            f"v{excl.version}, normalisation v{NORMALIZATION_VERSION}",
            "min_count": args.min_count,
            "scope": "letters: Latin and Greek; digits, punctuation, symbols: any; space",
            "unknown_handling": "lines with characters outside the charset are excluded from "
            "recognizer training and counted; in evaluation they count as errors",
            "normalization": {"version": NORMALIZATION_VERSION, "rules": NORMALIZATION_RULES},
            "coverage": cov,
        },
    )
    out = root / "manifests" / "charset.json"
    charset.save(out)

    g = git_info()
    report = [
        "# Character set report",
        "",
        f"Generated by `scripts/build_charset.py` on {datetime.now(UTC).date().isoformat()} from "
        f"commit `{(g.commit or 'unknown')[:7]}`. Do not edit by hand.",
        "",
        f"- Charset file: `data/manifests/charset.json` (version {charset.version}), "
        f"{len(chars)} characters + CTC blank = {charset.num_classes} classes.",
        f"- Rule: in-scope characters seen at least {args.min_count} times in HierText train "
        f"labels (exclusion list v{excl.version}, normalisation v{NORMALIZATION_VERSION}).",
        "",
        "## Coverage",
        "",
        "| Split | Lines | All characters | In-scope characters | Lines fully covered |",
        "|---|---|---|---|---|",
    ]
    for split in SPLITS:
        c = cov[split]
        report.append(
            f"| {split} | {stats[split]['lines']:,} | {c['characters_all']:.5f} | "
            f"{c['characters_in_scope']:.5f} | {c['lines_fully_covered']:.5f} |"
        )
    n_rare, n_oos = sum(rare.values()), sum(oos.values())
    report += [
        "",
        '"All characters" includes letters of scripts outside the English scope (ADR-0008), '
        'which the charset excludes on purpose; "in-scope" leaves them out.',
        "",
        "## Normalisation",
        "",
        *[f"- {r}" for r in NORMALIZATION_RULES],
        "",
        "| Split | Labels changed by normalisation | Labels empty after normalisation |",
        "|---|---|---|",
        *[
            f"| {s} | {stats[s].get('changed_by_normalisation', 0):,} | "
            f"{stats[s].get('empty_after_normalisation', 0):,} |"
            for s in SPLITS
        ],
        "",
        f"## Dropped from train counts ({len(rare)} rare, {n_rare:,} occurrences; "
        f"{len(oos)} out of scope, {n_oos:,} occurrences)",
        "",
        "Most frequent out-of-scope characters: "
        + ", ".join(
            _label(ch) + f" ({n})" for ch, n in sorted(oos.items(), key=lambda x: -x[1])[:15]
        ),
        "",
        "Most frequent rare characters: "
        + ", ".join(
            _label(ch) + f" ({n})" for ch, n in sorted(rare.items(), key=lambda x: -x[1])[:15]
        ),
        "",
        "## Characters",
        "",
        "| Index | Character | Train count |",
        "|---|---|---|",
        *[f"| {i} | {_label(ch)} | {counts['train'][ch]:,} |" for i, ch in enumerate(chars, 1)],
        "",
    ]
    rp = Path(args.reports) / "charset" / "charset_report.md"
    rp.parent.mkdir(parents=True, exist_ok=True)
    rp.write_text("\n".join(report), encoding="utf-8", newline="\n")
    print(f"{len(chars)} characters; validation in-scope coverage "
          f"{cov['validation']['characters_in_scope']:.5f}; wrote {out.as_posix()}")  # fmt: skip
    return 0


if __name__ == "__main__":
    sys.exit(main())
