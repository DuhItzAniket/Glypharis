# ------------------------------------------------------------------------------- the tree


def tree_state() -> dict[str, Any]:
    """The branch, the tree at `TAG` and the v1 code paths; refuses on any of them."""
    try:
        evsets.require_branch(BRANCH, REPO)
    except RuntimeError as exc:
        raise SystemExit(str(exc)) from exc
    try:
        pin = frozen.pinned_code_check(TAG, root=REPO)
    except RuntimeError as exc:
        raise SystemExit(f"the tree is not pinned at {TAG}: {exc}") from exc
    try:
        v1_code = v1code.assert_v1_code(REPO)
    except v1code.V1CodeError as exc:
        raise SystemExit(f"the v1 code is not v1's: {exc}") from exc
    return {"pinned": pin, "v1_code": v1_code}


def committed(path: Path) -> bool:
    """Whether ``path`` is tracked and HEAD holds it as it is on disk."""
    try:
        rel = path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return False
    tracked = subprocess.run(
        ["git", "ls-files", "--error-unmatch", "--", rel],
        cwd=REPO,
        capture_output=True,
        check=False,
    )
    clean = subprocess.run(
        ["git", "diff", "--quiet", "HEAD", "--", rel], cwd=REPO, capture_output=True, check=False
    )
    return tracked.returncode == 0 and clean.returncode == 0


def margin_for(arm: str | None) -> float:
    return INT8_MARGIN if arm == INT8_ARM else MARGIN


def bundle_identity() -> dict[str, Any]:
    """The frozen bundle this pass is about: its manifest hash, label, arm and margin."""
    live, record = BUNDLE / "manifest.json", BUNDLE_RECORD / "manifest.json"
    equivalence = BUNDLE_RECORD / "equivalence.json"
    for path, what in ((live, "the bundle's manifest"), (record, "the committed manifest")):
        if not path.is_file():
            raise SystemExit(f"{what} ({ps.shown(path)}) is missing")
    digest = sha256_file(live)
    if digest != sha256_file(record):
        raise SystemExit("the bundle's manifest differs from the committed copy (GW-EFF-014)")
    if not equivalence.is_file():
        raise SystemExit(f"{ps.shown(equivalence)} is missing: the bundle's check comes first")
    check = json.loads(equivalence.read_text(encoding="utf-8"))
    if check.get("pass") is not True or check.get("bundle_manifest_sha256") != digest:
        raise SystemExit(f"{ps.shown(equivalence)} does not pass this bundle")
    manifest = json.loads(live.read_text(encoding="utf-8"))
    label = manifest.get("version_label")
    if not isinstance(label, str) or label == V1_LABEL or "not v1" not in label:
        raise SystemExit("the bundle's version label does not say it is not v1")
    temperature = (manifest.get("recognizer") or {}).get("temperature")
    if temperature != TEMPERATURE:
        raise SystemExit(f"the bundle's temperature is {temperature}, not {TEMPERATURE}")
    arm = manifest.get("arm")
    return {
        "bundle_manifest_sha256": digest,
        "version": manifest.get("version"),
        "version_label": label,
        "arm": arm,
        "batching": manifest.get("batching"),
        "temperature": temperature,
        "margin": margin_for(arm),
    }


