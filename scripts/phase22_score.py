class Phase22Scorer(ps.Scorer):
    """The unchanged Phase 14 scorer, logging phase 22. ``ps.PHASE`` routes baseline paths."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self.ctx.phase = PHASE
