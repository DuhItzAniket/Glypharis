@contextlib.contextmanager
def patched(module: Any, **attrs: Any) -> Iterator[None]:
    """Module attributes for the length of a block, restored afterwards."""
    old = {k: getattr(module, k) for k in attrs}
    for k, v in attrs.items():
        setattr(module, k, v)
    try:
        yield
    finally:
        for k, v in old.items():
            setattr(module, k, v)


def score_as(sc: ps.Scorer, jobs: Sequence[ps.Job], label: str) -> None:
    """`Scorer.score_phase14` with every entry labelled ``label``."""
    with patched(ps, GLYPHARIS_VERSION=label):
        sc.score_phase14(jobs)


def _get(sc: ps.Scorer, experiment: str, task: str, eval_set: str) -> ps.Scored:
    s = sc.get(experiment, ps.GLYPHARIS, task, eval_set)
    if s is None or s.units is None:
        raise SystemExit(f"{experiment} {task} {eval_set} was not scored")
    return s


# ----------------------------------------------------------------------------- H11's tests


def _ratio(num: np.ndarray, den: np.ndarray) -> float | None:
    return float(num.sum() / den.sum()) if den.sum() else None


def _with_documents(
    res: dict[str, Any], docs: Interval, side: str, groups: Sequence[str]
) -> dict[str, Any]:
    unit_verdict = res["verdict"]
    doc_verdict = verdict(docs, side)
    return {
        **res,
        "documents": len(set(groups)),
        "document_interval": ps.iv(docs),
        "verdicts": {"units": unit_verdict, "documents": doc_verdict},
        "verdict": ps.combined([unit_verdict, doc_verdict]),
    }


def line_cer_test(
    c: ps.RecUnits,
    v: ps.RecUnits,
    m: float,
    groups: Sequence[str] | None = None,
    unit: str = "lines",
) -> dict[str, Any]:
    """`paired_ratio_diff_ci(e_c - m * n, e_v, n, unit)` below 0 on the strict track; with
    ``groups`` (one source document per crop) also by document, `combined`."""
    if c.keys != v.keys:
        raise SystemExit("the candidate's and v1's files cover other crops; scoring stops")
    a, b = c.tracks["strict"], v.tracks["strict"]
    if not np.array_equal(a["den"], b["den"]):
        raise SystemExit("the candidate's and v1's files disagree on the references; scoring stops")
    keep = a["den"] > 0
    e_c, e_v, n = a["err"][keep], b["err"][keep], a["den"][keep]
    units = paired_ratio_diff_ci(e_c - m * n, e_v, n, unit)
    res: dict[str, Any] = {
        "formula": f'paired_ratio_diff_ci(e_c - m * n, e_v, n, "{unit}")',
        "side": "below",
        "units": int(keep.sum()),
        "candidate": _ratio(e_c, n),
        "v1": _ratio(e_v, n),
        "interval": ps.iv(units),
        "verdict": verdict(units, "below"),
    }
    if groups is None:
        return res
    g = [grp for grp, k in zip(groups, keep, strict=True) if k]
    docs = cluster_paired_ratio_diff_ci(e_c - m * n, e_v, n, g, "documents")
    return _with_documents(res, docs, "below", g)


def page_cer_test(
    c: ps.PageUnits, v: ps.PageUnits, m: float, groups: Sequence[str] | None = None
) -> dict[str, Any]:
    """`paired_ratio_diff_ci(b_c - m * r, b_v, r, "pages")` below 0 (bag-of-lines, strict)."""
    if c.keys != v.keys:
        raise SystemExit("the candidate's and v1's files cover other pages; scoring stops")
    (b_c, r_c), (b_v, r_v) = ps._bag(c, "strict"), ps._bag(v, "strict")
    if not np.array_equal(r_c, r_v):
        raise SystemExit("the candidate's and v1's files disagree on the references; scoring stops")
    units = paired_ratio_diff_ci(b_c - m * r_c, b_v, r_c, "pages")
    res: dict[str, Any] = {
        "formula": 'paired_ratio_diff_ci(b_c - m * r, b_v, r, "pages")',
        "side": "below",
        "units": len(c.keys),
        "candidate": _ratio(b_c, r_c),
        "v1": _ratio(b_v, r_c),
        "interval": ps.iv(units),
        "verdict": verdict(units, "below"),
    }
    if groups is None:
        return res
    docs = cluster_paired_ratio_diff_ci(b_c - m * r_c, b_v, r_c, list(groups), "documents")
    return _with_documents(res, docs, "below", groups)


def _f1_parts(u: ps.PageUnits) -> tuple[np.ndarray, np.ndarray]:
    tp = u.arr("strict", lambda r: r.e2e_tp)
    return tp, u.arr("strict", lambda r: r.e2e_pred + r.e2e_gt)


def e2e_f1_test(
    c: ps.PageUnits, v: ps.PageUnits, m: float, groups: Sequence[str] | None = None
) -> dict[str, Any]:
    """`paired_ratios_diff_ci(2 * tp_c + m * d_c, d_c, 2 * tp_v, d_v, "pages")` above 0; by
    document, the four sums per document in one order, then the same interval."""
    if c.keys != v.keys:
        raise SystemExit("the candidate's and v1's files cover other pages; scoring stops")
    (tp_c, d_c), (tp_v, d_v) = _f1_parts(c), _f1_parts(v)
    parts = (2 * tp_c + m * d_c, d_c, 2 * tp_v, d_v)
    units = paired_ratios_diff_ci(*parts, "pages")
    res: dict[str, Any] = {
        "formula": 'paired_ratios_diff_ci(2 * tp_c + m * d_c, d_c, 2 * tp_v, d_v, "pages")',
        "side": "above",
        "units": len(c.keys),
        "candidate": _ratio(2 * tp_c, d_c),
        "v1": _ratio(2 * tp_v, d_v),
        "interval": ps.iv(units),
        "verdict": verdict(units, "above"),
    }
    if groups is None:
        return res
    g = np.asarray(list(groups), dtype=object)
    order = sorted(set(groups))
    num_c, den_c, num_v, den_v = (
        np.array([x[g == doc].sum() for doc in order], dtype=np.float64) for x in parts
    )
    docs = paired_ratios_diff_ci(num_c, den_c, num_v, den_v, "documents")
    return _with_documents(res, docs, "above", groups)


def overall(verdicts: Sequence[str]) -> str:
    """H11's rule: met only if every test is met; not met if any is; otherwise not shown."""
    if verdicts and all(v == "met" for v in verdicts):
        return "met"
    return "not met" if "not met" in verdicts else "not shown"


def three_tests(
    rec: tuple[ps.RecUnits, ps.RecUnits],
    pages: tuple[ps.PageUnits, ps.PageUnits],
    m: float,
    crop_groups: Sequence[str] | None = None,
    page_groups: Sequence[str] | None = None,
) -> dict[str, dict[str, Any]]:
    return {
        "line_cer": line_cer_test(*rec, m, crop_groups),
        "page_cer": page_cer_test(*pages, m, page_groups),
        "e2e_f1": e2e_f1_test(*pages, m, page_groups),
    }


def h11(
    cand: ps.Scorer, v1: ps.Scorer, m: float, sources: dict[str, str], ident: dict[str, Any]
) -> dict[str, Any]:
    tests: dict[str, dict[str, Any]] = {}
    for eval_set in H11_SETS:
        c_rec, v_rec = (
            _get(cand, REC_ID, "rec", eval_set),
            _get(v1, V1_PAIR[REC_ID], "rec", eval_set),
        )
        c_e2e = _get(cand, E2E_ID, "e2e", eval_set)
        v_e2e = _get(v1, V1_PAIR[E2E_ID], "e2e", eval_set)
        assert isinstance(c_rec.units, ps.RecUnits) and isinstance(v_rec.units, ps.RecUnits)
        assert isinstance(c_e2e.units, ps.PageUnits) and isinstance(v_e2e.units, ps.PageUnits)
        crop_groups = page_groups = None
        if eval_set == GDC:
            pages, crops = cand.ctx.pages(GDC), cand.pack(GDC)
            crop_groups = [sources[pages[crops[k].doc_id].image] for k in c_rec.units.keys]
            page_groups = [sources[pages[k].image] for k in c_e2e.units.keys]
        tests[eval_set] = three_tests(
            (c_rec.units, v_rec.units), (c_e2e.units, v_e2e.units), m, crop_groups, page_groups
        )
    verdicts = {
        f"{s} {name}": t["verdict"] for s, block in tests.items() for name, t in block.items()
    }
    return {
        "rule": "research/hypotheses.md, H11: six tests, all required; on GDC each test is also "
        "run with source documents as the unit and its verdict is the two verdicts combined",
        "margin": m,
        "arm": ident["arm"],
        "files": {
            "candidate": [REC_ID, E2E_ID],
            "v1": [V1_PAIR[REC_ID], V1_PAIR[E2E_ID]],
        },
        "tests": tests,
        "verdicts": verdicts,
        "verdict": overall(list(verdicts.values())),
        "holds": all(v == "met" for v in verdicts.values()),
    }


