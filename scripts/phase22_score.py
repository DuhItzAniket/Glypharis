def run_gate(args: argparse.Namespace) -> int:
    data: Path = args.data_root
    tree = tree_state()
    ident = bundle_identity()
    tag_commit = str(tree["pinned"]["tag_commit"])
    out = gate_path()
    if out.exists():
        raise SystemExit(f"{ps.shown(out)} exists: the gate is run once")
    cand_jobs, v1_gate = gate_jobs(data)
    v1_files = verify_v1(data, v1_gate)  # first, before anything is read from them
    ps.check_complete(data, [*cand_jobs, *v1_gate])
    check_candidate_meta(cand_jobs, ident, tag_commit)
    inputs = ps.check_job_inputs(data, [*cand_jobs, *v1_gate])
    sc = Phase22Scorer(data, ACCESS_LOG, GATE_REASON)
    score_as(sc, cand_jobs, ident["version_label"])
    score_as(sc, v1_gate, V1_LABEL)
    (c_rec, c_e2e), (v_rec, v_e2e) = (
        [_get(sc, j.experiment, j.task, GATE_SET).units for j in jobs]
        for jobs in (cand_jobs, v1_gate)
    )
    assert isinstance(c_rec, ps.RecUnits) and isinstance(v_rec, ps.RecUnits)
    assert isinstance(c_e2e, ps.PageUnits) and isinstance(v_e2e, ps.PageUnits)
    m = ident["margin"]
    tests = three_tests((c_rec, v_rec), (c_e2e, v_e2e), m)
    verdicts = {k: t["verdict"] for k, t in tests.items()}
    git = git_info(REPO)
    doc = {
        "note": GATE_NOTE,
        "what": "the candidate's validation gate (docs/PHASE_STATUS.md, Phase 22 item 18): H11's "
        "three formulas on HierText validation, unit intervals only; all three must be met "
        "before any test set is opened",
        "experiments": {exp: old for exp, (_, old) in GATE_RUNS.items()},
        "set": GATE_SET,
        "margin": m,
        "version_label": ident["version_label"],
        "arm": ident["arm"],
        "bundle_manifest_sha256": ident["bundle_manifest_sha256"],
        "tag": TAG,
        "tag_commit": tag_commit,
        "scorer": {"commit": git.commit, "branch": git.branch, "dirty": git.dirty},
        "v1_code": tree["v1_code"],
        "v1_files": v1_files,
        "inputs": inputs,
        "candidate": [s.entry for s in sc.scored.values() if s.job.phase == PHASE],
        "tests": tests,
        "verdicts": verdicts,
        "all_met": all(v == "met" for v in verdicts.values()),
        "verdict": overall(list(verdicts.values())),
        "date": datetime.now(UTC).date().isoformat(),
    }
    _write_json(out, doc)
    print(
        f"wrote {ps.shown(out)}: line CER {verdicts['line_cer']}, page CER "
        f"{verdicts['page_cer']}, E2E F1 {verdicts['e2e_f1']}"
    )
    return 0 if doc["all_met"] else 1


def run_hashes(args: argparse.Namespace) -> int:
    data: Path = args.data_root
    tree = tree_state()
    ident = bundle_identity()
    tag_commit = str(tree["pinned"]["tag_commit"])
    if (data / PASS_RECORD).exists():
        raise SystemExit(
            f"data/{PASS_RECORD.as_posix()} exists: the hashes are written before scoring"
        )
    jobs = candidate_jobs(data)
    ps.check_complete(data, jobs)
    check_candidate_meta(jobs, ident, tag_commit)
    doc = {
        "note": HASHES_NOTE,
        "experiments": sorted(TEST_RUNS),
        "bundle_manifest_sha256": ident["bundle_manifest_sha256"],
        "tag": TAG,
        "tag_commit": tag_commit,
        "files": hash_entries(data, jobs),
    }
    path = hashes_path()
    if path.exists():
        old = json.loads(path.read_text(encoding="utf-8"))
        if old != doc:
            raise SystemExit(f"{ps.shown(path)} exists and differs; it is never rewritten")
        print(f"{len(jobs)} prediction files match {ps.shown(path)}")
        return 0
    _write_json(path, doc)
    print(f"hashed {len(jobs)} prediction files into {ps.shown(path)}; commit it before scoring")
    return 0


def run_score(args: argparse.Namespace) -> int:
    data: Path = args.data_root
    tree = tree_state()
    ident = bundle_identity()
    tag_commit = str(tree["pinned"]["tag_commit"])
    out = REPORTS
    opts = ps.Options(data, out, out, ACCESS_LOG, ps.FREEZE_RECORD, args.resume)
    with patched(ps, PASS_RECORD=PASS_RECORD, OFFICIAL=OFFICIAL, HANDOFF=HANDOFF):
        state, resuming = ps.start_pass(opts)  # one-shot; a stopped pass only with --resume
        return _score(data, out, tree, ident, tag_commit, state, resuming)


def _score(
    data: Path,
    out: Path,
    tree: dict[str, Any],
    ident: dict[str, Any],
    tag_commit: str,
    state: dict[str, Any],
    resuming: bool,
) -> int:
    # Preflight: every refusal before the pass is marked started and before any row is logged.
    if not ACCESS_LOG.is_file():
        raise SystemExit(f"the test-access log {ps.shown(ACCESS_LOG)} does not exist")
    cand_jobs, old_jobs = candidate_jobs(data), v1_jobs(data)
    v1_files = verify_v1(data, old_jobs)  # item 20: stop if v1's files do not match
    counts = ps.check_complete(data, [*cand_jobs, *old_jobs])
    check_candidate_meta(cand_jobs, ident, tag_commit)
    gate = check_gate(ident, tag_commit)
    hashes = check_hashes(data, cand_jobs, ident)
    inputs = ps.check_job_inputs(data, [*cand_jobs, *old_jobs])
    evaluators = ps.check_evaluators(data)
    converted = dry_convert(data, cand_jobs)
    rescored = {(j.experiment, j.eval_set) for j in old_jobs}
    reported = v1_reported(V1_REPORT, rescored)
    conditions, sources = ps.gdc_conditions(), ps.gdc_sources()

    reason = REASON + ps.RESUMED if resuming else REASON
    if resuming and (data / OFFICIAL).exists():
        shutil.rmtree(data / OFFICIAL)  # the pass's own work folder; written again below
    record = {
        "experiment": EXPERIMENT,
        "status": "started",
        "started_utc": state.get("started_utc") or _now(),
        "resumed_utc": [*state.get("resumed_utc", []), *([_now()] if resuming else [])],
        "reason": reason,
    }
    ps.write_pass(data, record)  # before the first logged row

    cand = Phase22Scorer(data, ACCESS_LOG, reason)
    score_as(cand, cand_jobs, ident["version_label"])
    v1 = Phase22Scorer(data, ACCESS_LOG, reason)
    score_as(v1, old_jobs, V1_LABEL)
    entries = [s.entry for s in cand.scored.values()]
    if any(e.get("version") != ident["version_label"] for e in entries):
        raise SystemExit("a candidate entry is not labelled with the bundle's label")
    candidate = {
        "label": ident["version_label"],
        "predictions": entries,
        "subset": cand.subset_entries(),
        "gdc_conditions": cand.gdc_condition_tables(conditions),
        "gdc_scan_in_charset": cand.gdc_scan_in_charset(),
        "gdc_scan_in_charset_pages": cand.gdc_scan_in_charset_pages(),
        # Only `cand`'s files reach the official evaluators.
        "official": {
            "hiertext": cand.official_hiertext(data / OFFICIAL),
            "omnidocbench": cand.official_omnidocbench(data / OFFICIAL),
            "evaluators": evaluators,
        },
        "calibration": calibration(cand),
    }
    hyp = h11(cand, v1, ident["margin"], sources, ident)
    git = git_info(REPO)
    res = {
        "experiment": EXPERIMENT,
        "note": NOTE,
        "provenance": {
            "scorer": {"commit": git.commit, "branch": git.branch, "dirty": git.dirty},
            "tree": tree,
            "bundle": ident,
            "date": datetime.now(UTC).date().isoformat(),
            "access_log_reason": reason,
            "pass": {k: record[k] for k in ("started_utc", "resumed_utc")},
            "files": len(counts),
            "gate": gate,
            "prediction_hashes": hashes,
            "v1_files": v1_files,
            "inputs": inputs,
            "converted": converted,
        },
        "candidate": candidate,
        "v1": {
            "label": V1_LABEL,
            "rescored": [s.entry for s in v1.scored.values()],
            "reported": reported,
        },
        "h11": hyp,
    }
    out.mkdir(parents=True, exist_ok=True)
    for name, text in (("results.md", render_results(res)), ("h11.md", render_h11(res))):
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    _write_json(out / "results.json", res)
    ps.write_pass(data, {**record, "status": "done", "ended_utc": _now()})
    tests = sum(len(b) for b in hyp["tests"].values())
    print(f"wrote {ps.shown(out)}: H11 {hyp['verdict']} ({tests} tests)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("command", choices=("gate", "hashes", "score"))
    parser.add_argument("--data-root", type=Path, default=REPO / "data")
    parser.add_argument(
        "--resume",
        action="store_true",
        help="score: finish a pass that started and stopped (its rows are logged as resumed)",
    )
    args = parser.parse_args(argv)
    if args.resume and args.command != "score":
        raise SystemExit("--resume is for score")
    if args.command == "gate":
        return run_gate(args)
    if args.command == "hashes":
        return run_hashes(args)
    return run_score(args)


if __name__ == "__main__":
    sys.exit(main())
