def _set(e: dict[str, Any]) -> str:
    return e["eval_set"] + (f" ({e['subset']})" if e.get("subset") else "")


def _n(e: dict[str, Any]) -> str:
    return f"{e['samples']:,}" + ("" if e["samples"] == e["expected"] else f" of {e['expected']:,}")


def _num(x: Any, digits: int = 4) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def render_results(res: dict[str, Any]) -> str:
    """The candidate's own figures. Nothing of v1's is in this file."""
    c = res["candidate"]
    entries = c["predictions"]
    order = {s: i for i, s in enumerate(EVAL_SETS)}
    entries = sorted(entries, key=lambda e: (order[e["eval_set"]], e["experiment"]))
    rec = [e for e in entries if e["task"] == "rec"]
    pages = [e for e in entries if e["task"] != "rec"]
    lines = [
        f"# Phase 22: the phone candidate on the test sets ({EXPERIMENT})",
        "",
        f"{NOTE} Version: {c['label']}. Values in % with the 95% bootstrap CI over lines (words "
        "for IIIT5K) or pages. The charset ceiling is the share of reference characters outside "
        "the charset. GDC-scan is one document: numbers only.",
        "",
        f"Bundle manifest SHA-256 `{res['provenance']['bundle']['bundle_manifest_sha256']}`, arm "
        f"`{res['provenance']['bundle']['arm']}`, tag `{TAG}` at "
        f"`{res['provenance']['tree']['pinned']['tag_commit']}`.",
        "",
    ]
    for t in ps.TRACKS:
        rows = [
            [
                e["experiment"],
                _set(e),
                _n(e),
                ps.pct(e["tracks"][t]["cer"]),
                ps.pct(e["tracks"][t]["wer"]),
                f"{100 * e['tracks'][t]['sequence_accuracy']:.2f}",
                f"{100 * e['tracks'][t]['charset_ceiling']:.2f}",
            ]
            for e in rec
        ]
        head = ["ID", "Set", "Lines", "CER %", "WER %", "Seq acc %", "Charset ceiling %"]
        lines += [f"## Recognition, track: {t}", "", *ps.table(head, rows)]
    alnum = [e for e in rec if ps.ALNUM in e["tracks"]]
    if alnum:
        rows = [
            [e["experiment"], _n(e), ps.pct(e["tracks"][ps.ALNUM]["word_accuracy"]),
             ps.pct(e["tracks"][ps.ALNUM]["cer"])]
            for e in alnum
        ]  # fmt: skip
        lines += ["## IIIT5K, alphanumeric track", "", *ps.table(["ID", "Words", "Word acc %",
                                                                  "CER %"], rows)]  # fmt: skip
    for t in ps.TRACKS:
        rows = []
        for e in [*pages, *c["subset"]]:
            tr = e["tracks"][t]
            det = (e.get("detection") or {}).get("iou_0.5", {}).get("f1") if t == "strict" else None
            rows.append(
                [
                    e["experiment"],
                    _set(e),
                    _n(e),
                    ps.pct(tr.get("page_cer_bag_of_lines")),
                    ps.pct(tr.get("page_cer_order_aware")),
                    ps.pct(tr.get("e2e_f1")),
                    ps.pct(det) if t == "strict" else "",
                    f"{100 * tr['charset_ceiling']:.2f}",
                ]
            )
        head = ["ID", "Set", "Pages", "Bag-of-lines CER %", "Order-aware CER %", "E2E F1 %",
                "Det F1@0.5 %", "Charset ceiling %"]  # fmt: skip
        lines += [f"## End to end, track: {t}", "", *ps.table(head, rows)]
    if c["gdc_scan_in_charset"]:
        rows = [
            [r["experiment"], f"{r['lines']:,}", str(r["left_out"]),
             ps.pct(r["tracks"]["strict"]["cer"]), ps.pct(r["tracks"]["normalised"]["cer"])]
            for r in c["gdc_scan_in_charset"]
        ]  # fmt: skip
        lines += [
            "## GDC-scan without out-of-charset lines (information)",
            "",
            *ps.table(["ID", "Lines", "Left out", "CER % strict", "CER % normalised"], rows),
        ]
    off = c["official"]
    if off["hiertext"]:
        rows = [
            [r["experiment"], str(r["pages"]),
             ", ".join(f"{k} {_num(v)}" for k, v in sorted(r["line"].items())
                       if isinstance(v, int | float))]
            for r in off["hiertext"]
        ]  # fmt: skip
        lines += ["## Official HierText, line level", "",
                  *ps.table(["ID", "Pages", "Scores"], rows)]  # fmt: skip
    if off["omnidocbench"]:
        rows = [
            [r["experiment"], r["scope"], str(r["pages"]),
             _num(r["text_block"]["edit_whole"]), _num(r["text_block"]["edit_sample_avg"]),
             _num(r["reading_order"]["edit_whole"])]
            for r in off["omnidocbench"]
        ]  # fmt: skip
        head = ["ID", "Scope", "Pages", "Text block edit (whole)", "Text block edit (page avg)",
                "Reading order edit (whole)"]  # fmt: skip
        lines += ["## Official OmniDocBench", "", *ps.table(head, rows)]
    cal = c["calibration"]
    rows = [
        [s, f"{b['lines']:,}", b["track"], _num(b["ece_t1"]), _num(b["ece_t"])]
        for s, b in cal["sets"].items()
    ]
    pl = cal["gdc_pipeline_lines"]
    rows.append(["gdc_test pipeline lines", f"{pl['lines']:,}", pl["track"], _num(pl["ece_t1"]),
                 _num(pl["ece_t"])])  # fmt: skip
    lines += [
        f"## Calibration at T = {cal['temperature']} (information)",
        "",
        *ps.table(["Set", "Lines", "Track", "ECE T = 1", f"ECE T = {cal['temperature']}"], rows),
    ]
    return "\n".join(lines)


def render_h11(res: dict[str, Any]) -> str:
    h = res["h11"]
    lines = [
        f"# Phase 22: H11, the phone candidate against v1 ({EXPERIMENT})",
        "",
        f"{NOTE} {h['rule']}. Margin m = {h['margin']} (arm `{h['arm']}`); strict track. "
        f"Candidate: {', '.join(h['files']['candidate'])} ({res['candidate']['label']}). "
        f"v1: {', '.join(h['files']['v1'])}, checked against phase14_outputs.json first.",
        "",
        f"**H11: {h['verdict']}.**",
        "",
    ]
    rows = []
    for eval_set, block in h["tests"].items():
        for name, t in block.items():
            rows.append(
                [
                    eval_set,
                    name,
                    str(t["units"]),
                    _num(t["candidate"]),
                    _num(t["v1"]),
                    ps.pp(t["interval"], digits=3),
                    t["verdicts"]["units"] if "verdicts" in t else t["verdict"],
                    ps.pp(t["document_interval"], digits=3) if "document_interval" in t else "",
                    t["verdicts"]["documents"] if "verdicts" in t else "",
                    t["verdict"],
                ]
            )
    head = ["Set", "Test", "Units", "Candidate", "v1", "Interval (points)", "Unit verdict",
            "Document interval (points)", "Document verdict", "Verdict"]  # fmt: skip
    lines += ps.table(head, rows)
    return "\n".join(lines)


