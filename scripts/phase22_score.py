def verify_v1(data: Path, jobs: Sequence[ps.Job]) -> list[dict[str, Any]]:
    """v1's files and their run metadata, each as phase14_outputs.json records it, or stop."""
    missing = [j.label for j in jobs if not j.path.is_file()]
    missing += [j.label for j in jobs if not j.path.with_suffix(".meta.json").is_file()]
    if missing:
        raise SystemExit(f"v1's files are missing: {sorted(set(missing))}")
    entries = [ps.file_entry(j.path, data) for j in jobs]
    unrecorded = ps.check_outputs(data, entries)  # stops on a different hash or count
    if unrecorded:
        raise SystemExit(
            f"{len(unrecorded)} of v1's files are not in {ps.OUTPUTS.as_posix()}, e.g. "
            f"{unrecorded[0]['file']}; scoring stops"
        )
    return entries


def _bundle_hash(meta: dict[str, Any]) -> str | None:
    for key in ("bundle_manifest_sha256", "bundle_sha256"):
        block = ps._find(meta, key)
        if block is not None:
            return str(block[key])
    return None


def check_candidate_meta(
    jobs: Sequence[ps.Job], ident: dict[str, Any], tag_commit: str
) -> dict[str, Any]:
    """Every candidate file was written by this bundle at this tag, and its last run finished."""
    problems = []
    for job in jobs:
        meta = json.loads(job.path.with_suffix(".meta.json").read_text(encoding="utf-8"))
        if meta.get("experiment") != job.experiment or meta.get("eval_set") not in (
            None,
            job.eval_set,
        ):
            problems.append(f"{job.label}: its metadata names another run")
        if meta.get("smoke") is not None:
            problems.append(f"{job.label}: a smoke run, never scored")
        runs = meta.get("runs") or []
        if not runs or runs[-1].get("status") != "done":
            problems.append(f"{job.label}: its last run did not finish")
        if _bundle_hash(meta) != ident["bundle_manifest_sha256"]:
            problems.append(f"{job.label}: written by another bundle")
        pin = ps._find_pin(meta) or {}
        if (pin.get("tag"), pin.get("trees"), pin.get("tag_commit")) != (TAG, "equal", tag_commit):
            problems.append(f"{job.label}: not run at {TAG} ({tag_commit[:12]})")
    if problems:
        raise SystemExit(
            "the candidate's files are not this bundle's runs at the tag; nothing is scored:\n  "
            + "\n  ".join(problems)
        )
    return {"files": len(jobs), "bundle_manifest_sha256": ident["bundle_manifest_sha256"]}


def _count(path: Path) -> int:
    return sum(1 for ln in path.read_bytes().splitlines() if ln.strip())


def hash_entries(data: Path, jobs: Sequence[ps.Job]) -> list[dict[str, Any]]:
    out = []
    for job in jobs:
        meta = job.path.with_suffix(".meta.json")
        out.append(
            {
                "experiment": job.experiment,
                "task": job.task,
                "eval_set": job.eval_set,
                "file": ps.data_rel(job.path, data),
                "sha256": sha256_file(job.path),
                "lines": _count(job.path),
                "meta": ps.data_rel(meta, data),
                "meta_sha256": sha256_file(meta),
                "meta_lines": _count(meta),
            }
        )
    return out


def check_gate(ident: dict[str, Any], tag_commit: str) -> dict[str, Any]:
    """The gate's file: all three tests met, for this bundle and this tag commit."""
    path = gate_path()
    if not path.is_file():
        raise SystemExit(f"{ps.shown(path)} is missing: the validation gate comes first")
    doc = json.loads(path.read_text(encoding="utf-8"))
    verdicts = doc.get("verdicts") or {}
    if len(verdicts) != 3 or any(v != "met" for v in verdicts.values()) or not doc.get("all_met"):
        raise SystemExit(f"{ps.shown(path)}: not all three gate tests are met")
    if doc.get("bundle_manifest_sha256") != ident["bundle_manifest_sha256"]:
        raise SystemExit(f"{ps.shown(path)} was written for another bundle")
    if doc.get("tag_commit") != tag_commit:
        raise SystemExit(f"{ps.shown(path)} was written at another tag commit")
    return {"file": ps.shown(path), "sha256": sha256_file(path), "verdicts": verdicts}


def check_hashes(data: Path, jobs: Sequence[ps.Job], ident: dict[str, Any]) -> dict[str, Any]:
    """prediction_hashes.json is committed and still describes the files byte for byte."""
    path = hashes_path()
    if not path.is_file():
        raise SystemExit(f"{ps.shown(path)} is missing: run `hashes` and commit it first")
    if not committed(path):
        raise SystemExit(f"{ps.shown(path)} is not committed as it stands; commit it first")
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("bundle_manifest_sha256") != ident["bundle_manifest_sha256"]:
        raise SystemExit(f"{ps.shown(path)} was written for another bundle")
    if doc.get("files") != hash_entries(data, jobs):
        raise SystemExit(f"the prediction files differ from {ps.shown(path)}; scoring stops")
    return {"file": ps.shown(path), "sha256": sha256_file(path), "files": len(jobs)}


def dry_convert(data: Path, jobs: Sequence[ps.Job]) -> dict[str, int]:
    """Convert the candidate's HierText and OmniDocBench page files as the official step will, in
    a temporary folder under the pass's own folder, before any row is logged. Prediction files
    only, never the ground truth (as `phase14_score.dry_convert`, which works under Phase 14's)."""
    hier = [j for j in jobs if j.task == "e2e" and j.eval_set == "hiertext_test"]
    odb = [j for j in jobs if j.task == "e2e" and j.eval_set == "omnidocbench_test"]
    problems = []
    parent = data / WORK
    made = not parent.exists()
    parent.mkdir(parents=True, exist_ok=True)
    try:
        with tempfile.TemporaryDirectory(prefix="preflight-", dir=parent) as tmp:
            work = Path(tmp)
            ids = ps.full_keys(data, "hiertext_test", "e2e") if hier else []
            for i, job in enumerate(hier):
                try:
                    pred = official_hiertext.to_hiertext_predictions(
                        eb.read_records(job.path), image_ids=ids
                    )
                    official_hiertext.write_predictions(pred, work / "hiertext" / f"{i}.json")
                except (ValueError, KeyError, TypeError, OSError) as exc:
                    problems.append(f"{job.label}: {type(exc).__name__}")
            pages: dict[str, Any] = {}
            scopes: dict[str, set[str]] = {}
            if odb:
                odb_pages = data / EVAL_SETS["omnidocbench_test"]["pages"]
                pages = {p.doc_id: p for p in read_pages(odb_pages)}
                scopes = {"all": set(pages), SUBSET_NAME: set(subset_pages(data))}
            for i, job in enumerate(odb):
                try:
                    records = eb.read_records(job.path)
                    for scope, keep in scopes.items():
                        official_omnidocbench.write_predictions(
                            [
                                {**r, "image": pages[str(r["key"])].image}
                                for r in records
                                if str(r["key"]) in keep
                            ],
                            work / "omnidocbench" / f"{i}_{scope}",
                        )
                except (ValueError, KeyError, TypeError, OSError) as exc:
                    problems.append(f"{job.label}: {type(exc).__name__}")
    finally:
        if made and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
    if problems:
        raise SystemExit(
            "a prediction file cannot be converted for its official evaluator; nothing is "
            "scored:\n  " + "\n  ".join(problems)
        )
    return {"hiertext": len(hier), "omnidocbench": len(odb)}


