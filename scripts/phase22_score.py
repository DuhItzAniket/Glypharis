def calibration(sc: ps.Scorer) -> dict[str, Any]:
    """Reliability and ECE at T = 1 and at the bundle's T, on every candidate crop set and on
    GDC's pipeline lines (information; H8′ is v1's and is not re-tested)."""
    out: dict[str, Any] = {"temperature": TEMPERATURE, "sets": {}}
    for eval_set in TEST_RUNS[REC_ID][1]:
        s = _get(sc, REC_ID, "rec", eval_set)
        assert s.records is not None and s.units is not None
        keys = list(s.units.keys)
        track: Any = ps.ALNUM if eval_set == "iiit5k_test" else "strict"
        y = ps.correct_flags(s.records, keys, track)
        ct, ct1 = ps.confidences(s.records, keys)
        clusters = None
        if eval_set == GDC:
            crops = sc.pack(eval_set)
            clusters = [crops[k].doc_id for k in keys]
        out["sets"][eval_set] = {
            "experiment": REC_ID,
            **ps.calibration_block(ct, ct1, y, track, clusters, "pages"),
        }
    g = _get(sc, E2E_ID, "e2e", GDC)
    assert g.records is not None and g.units is not None
    out["gdc_pipeline_lines"] = ps.pipeline_calibration(sc.ctx.pages(GDC), g.records, g.units.keys)
    return out


def v1_reported(path: Path, rescored: set[tuple[str, str]]) -> dict[str, Any]:
    """v1's figures that are not re-scored here, copied from its Phase 14 report."""
    if not path.is_file():
        raise SystemExit(f"{ps.shown(path)} is missing: v1's other figures are copied from it")
    doc = json.loads(path.read_text(encoding="utf-8"))
    preds = [
        e
        for e in doc.get("predictions", [])
        if e.get("system") == ps.GLYPHARIS and (e["experiment"], e["eval_set"]) not in rescored
    ]
    official = {
        k: [r for r in (doc.get("official") or {}).get(k, []) if r.get("system") == ps.GLYPHARIS]
        for k in ("hiertext", "omnidocbench")
    }
    return {
        "source": ps.shown(path),
        "sha256": sha256_file(path),
        "experiment": doc.get("experiment"),
        "label": V1_LABEL,
        "predictions": preds,
        "official": official,
    }


