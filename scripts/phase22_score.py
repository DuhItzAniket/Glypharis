"""The phone candidate's scorer (Phase 22, items 17, 18 and 20): the gate, the hashes, GW-E2E-021.

    PYTHONPATH='.;scripts' $PY scripts/phase22_score.py gate      # item 18, before any test set
    PYTHONPATH='.;scripts' $PY scripts/phase22_score.py hashes    # item 19, after the 10 test runs
    PYTHONPATH='.;scripts' $PY scripts/phase22_score.py score     # item 20, the one scoring pass
    PYTHONPATH='.;scripts' $PY scripts/phase22_score.py score --resume

Every command starts on `BRANCH` with the tree pinned at `TAG` (`pinned_code_check`) and the v1
code paths equal to their tag (`assert_v1_code`), and checks the bundle: the SHA-256 of
`BUNDLE`/manifest.json must equal the committed copy under `BUNDLE_RECORD`, whose
``equivalence.json`` must say ``"pass": true`` for that hash. The candidate's prediction files
(written by `scripts/phase22_eval.py` under data/processed/phase22/<ID>/, in Phase 14's record
schema) must be complete, name that bundle hash and the tag's commit in their metadata, and have
a last run that is ``done``. v1's Phase 14 files are checked against
data/manifests/processed/phase14_outputs.json before anything else is read from them.

- ``gate`` scores GW-REC-044 against GW-REC-038 and GW-E2E-019 against GW-E2E-006 on HierText
  validation with H11's three formulas (unit intervals only) and writes
  reports/final_validation/candidate/validation_gate.json once: the verdicts, the bundle hash and
  the tag commit. A validation split logs no access row.
- ``hashes`` writes reports/final_validation/candidate/prediction_hashes.json: the SHA-256 and line
  counts of the 10 test prediction files and their metadata. It is committed before ``score``,
  which refuses it missing, uncommitted or different from the files.
- ``score`` is GW-E2E-021, once. data/processed/phase22/GW-E2E-021/pass.json follows the rules of
  `phase14_score.start_pass`: a finished pass or an existing results.json is refused, and a started
  pass that stopped needs ``--resume`` (its rows then say "(resumed)"). All three gate tests must be
  met for this bundle and tag. The candidate's 10 files are scored in one `Scorer`, with
  ``GLYPHARIS_VERSION`` set to the bundle's own label, which says it is not v1; v1's 4 files that
  H11 reads (GW-REC-039 and GW-E2E-007 on HierText test and GDC) go through `eb.score_file` in a
  second `Scorer` under v1's label. Every row says phase 22 and "Phase 22 candidate scoring
  (GW-E2E-021)": 14 in all. The official HierText and OmniDocBench scores read only the first
  `Scorer`'s files, so they score the candidate alone. Then H11's six tests, with the GDC source-
  document check (`combined`), and calibration at the bundle's temperature (2.35, unchanged). v1's
  other figures are copied from reports/external/results.json; its other test files are not read.
  Reports go to reports/final_validation/candidate/: results.json, results.md (the candidate only)
  and h11.md.

Nothing protected is edited and nothing of Phase 14's is written: the scorer reuses
`phase14_score` and `evaluate_baselines` by changing module attributes in its own process (the
pass record and the official work folder move under data/processed/phase22/GW-E2E-021/), and never
calls `ext_eval.record_output`, `ps.run_score`, `ps.preflight`, `ps.dry_convert`,
`ps.record_outputs` or `ps.drop_handoff_outputs`. GDC-scan contributes numbers only: no text,
image or file name of it is printed or written.

Bootstrap: `glypharis.eval.stats` defaults (1,000 resamples, seed 20261010, 95% percentile).
"""

