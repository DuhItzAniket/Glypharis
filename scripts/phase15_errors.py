def glyphsynth(
    rows: Sequence[Mapping[str, Any]], allowed: Mapping[str, frozenset[str]]
) -> dict[str, Any]:
    """GW-REC-041's slices: font family and category, italic, inverted, neighbour fragments,
    underline and the capture steps; line bootstrap (validation only). No held-out-font slice:
    every validation line uses a validation font. The charset ceiling counts the reference
    characters outside the GLYPHARIS charset."""
    out: dict[str, Any] = {"lines": len(rows), "tracks": {}}
    steps = sorted({s for r in rows for s in r.get("capture") or []})
    for t in TRACKS:
        ci = t == "strict"
        units = []
        for r in rows:
            s = score_pair(str(r["pred"]), str(r["ref"]), t)
            if s.ref_chars == 0:
                continue
            units.append(
                {
                    "char_errors": s.char_errors,
                    "ref_chars": s.ref_chars,
                    "oov_chars": sum(c not in allowed[t] for c in normalise(str(r["ref"]), t)),
                    **{k: r.get(k) for k in ("family", "category", *SYNTH_FLAGS)},
                    "capture": set(r.get("capture") or []),
                }
            )
        b: dict[str, Any] = {
            "empty_references": len(rows) - len(units),
            "ceiling": ceiling_of(units),
            "totals": slice_table(units, lambda u: "all", ci=ci),
            "family": slice_table(units, lambda u: u["family"], ci=ci),
            "category": slice_table(units, lambda u: u["category"], ci=ci),
        }
        for flag in SYNTH_FLAGS:
            b[flag] = slice_table(units, by_flag(flag), ci=ci)
        b["capture_steps"] = {
            step: slice_table(units, by_capture((step,)), ci=ci) for step in steps
        }
        b["capture_groups"] = {
            name: slice_table(units, by_capture(group), ci=ci)
            for name, group in CAPTURE_GROUPS.items()
        }
        out["tracks"][t] = b
    return out


