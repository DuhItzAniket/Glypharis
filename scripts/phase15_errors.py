# ---------------------------------------------------------------------------- 1. the inputs


def verify_inputs(data: Path, results: Path) -> dict[str, Any]:
    """Every file check of plan item 1, bytes only, before any row is read; a refusal is a
    SystemExit. The crops are checked later (`verify_crops`), once the edges are fixed.

    Returns the read record (``inputs``) and the Phase 5 check's result."""
    record: list[dict[str, Any]] = []
    p14 = [*handoff_files(data), data / VAL_FILE, *(p for _, p in odb_files(data))]
    missing = [ps.data_rel(p, data) for p in p14 if not p.is_file()]
    if missing:
        raise SystemExit(f"Phase 14 inputs are missing, e.g. {missing[0]}; nothing is read")
    entries = [ps.file_entry(p, data) for p in p14]
    new = ps.check_outputs(data, entries)  # raises on a hash or count that differs
    if new:
        raise SystemExit(
            f"{len(new)} Phase 14 inputs are not recorded in data/{ps.OUTPUTS.as_posix()}, e.g. "
            f"{new[0]['file']}; nothing is read"
        )
    record += [
        {**e, "check": f"data/{ps.OUTPUTS.as_posix()}", "checked_utc": _now()} for e in entries
    ]
    phase5 = ps.verify_phase5(data)  # read-only; raises on any changed file
    for files in phase5_rec_files(data).values():
        for _, path in files:
            if not path.is_file():
                raise SystemExit(f"{ps.data_rel(path, data)} is missing; nothing is read")
            record.append(
                {**ps.file_entry(path, data), "check": phase5["record"], "checked_utc": _now()}
            )
    for path in (data / CHARSET, data / GDC_SOURCES, data / GDC_SELECTION, results):
        if not path.is_file():
            raise SystemExit(f"{_shown(path, data)} is missing; nothing is read")
        record.append(
            {
                "file": _shown(path, data),
                "sha256": sha256_file(path),
                "lines": None,
                "check": "read as committed",
                "checked_utc": _now(),
            }
        )
    synth = data / SYNTH_FILE
    if synth.is_file():
        meta_path = synth.with_name(synth.name.removesuffix(".jsonl") + ".meta.json")
        if not meta_path.is_file():
            raise SystemExit(f"{ps.data_rel(synth, data)} has no .meta.json; nothing is read")
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        entry = ps.file_entry(synth, data)
        wrong = {k: meta.get(k) for k, v in SYNTH_META.items() if meta.get(k) != v}
        if wrong:
            raise SystemExit(
                f"{entry['file']}'s .meta.json names {wrong}, not {SYNTH_META}; nothing is read"
            )
        if meta.get("output_sha256") != entry["sha256"] or meta.get("count") != entry["lines"]:
            raise SystemExit(
                f"{entry['file']} differs from the hash or count in its .meta.json; nothing is read"
            )
        if meta.get("limit") is not None:
            raise SystemExit(f"{entry['file']} is a --limit smoke run, not the registered run")
        record.append({**entry, "check": ps.data_rel(meta_path, data), "checked_utc": _now()})
    return {"inputs": record, "phase5": phase5}


def verify_crops(data: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Each GDC crop of the hand-off against its SHA-256 in ``gdc_crops/index.jsonl`` (itself
    checked by `verify_inputs`); run after the edges are fixed, as the index holds test rows.

    Returns the index rows and one read record per crop (file, SHA-256, UTC time)."""
    index = handoff_path(data, "gdc_crops/index.jsonl")
    rows = read_jsonl(index)
    record = []
    for row in rows:
        path = index.parent / str(row["file"])
        if not path.is_file() or sha256_file(path) != row["sha256"]:
            raise SystemExit(
                f"the crop {row['file']} differs from its SHA-256 in gdc_crops/index.jsonl; "
                "nothing is read"
            )
        record.append(
            {
                "file": ps.data_rel(path, data),
                "sha256": str(row["sha256"]),
                "lines": None,
                "check": "gdc_crops/index.jsonl",
                "checked_utc": _now(),
                "crop": True,
            }
        )
    return rows, record


# ------------------------------------------------------------------------------- 2. the edges


def validation_edges(val_rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Quartile edges of GW-REC-038's values (lines with a non-empty strict reference), and the
    validation lines per bin."""
    rows = [r for r in val_rows if normalise(str(r["ref"]), "strict")]
    values: dict[str, list[float | None]] = {
        "line_height_px": [r.get("line_height_px") for r in rows],
        "blur": [r.get("blur") for r in rows],
        "contrast": [r.get("contrast") for r in rows],
        "length": [float(len(normalise(str(r["ref"]), "strict"))) for r in rows],
        "confidence": [r.get("conf_t") for r in rows],
    }
    out: dict[str, Any] = {}
    for name in EDGE_FIELDS:
        edges = er.quantile_edges(values[name])
        counts = Counter(er.bin_of(v, edges) for v in values[name])
        labels = er.bin_labels(edges)
        out[name] = {
            "edges": list(edges),
            "labels": labels,
            "validation_lines": [counts.get(i, 0) for i in range(len(labels))],
            "missing": counts.get(None, 0),
        }
    return out


def _edges(edges: Mapping[str, Any], name: str) -> tuple[float, ...]:
    return tuple(edges[name]["edges"])


# --------------------------------------------------------------------------- 3. consistency


def p14_entry(results: Mapping[str, Any], experiment: str, task: str, eval_set: str) -> Any:
    hits = [
        e
        for e in results.get("predictions", [])
        if (e.get("experiment"), e.get("system"), e.get("task"), e.get("eval_set"))
        == (experiment, GLYPHARIS, task, eval_set)
        and not e.get("subset")
    ]
    if len(hits) != 1:
        raise SystemExit(
            f"results.json holds {len(hits)} {experiment} {task} entries for {eval_set}, not one"
        )
    return hits[0]


def _float(x: Any) -> float | None:
    return None if x is None else float(x)


def _value(block: Any) -> float | None:
    return None if block is None else float(block["value"])


def _agree(what: str, got: float | None, want: float | None, problems: list[str]) -> None:
    if (got is None) != (want is None) or (
        got is not None and want is not None and abs(got - want) > 1e-9
    ):
        problems.append(f"{what}: the hand-off gives {got}, results.json {want}")


def _line_cer(rows: Iterable[Mapping[str, Any]], track: str) -> float | None:
    err = ref = 0
    for r in rows:
        t = r[track]
        if int(t["ref_chars"]) > 0:
            err += int(t["char_errors"])
            ref += int(t["ref_chars"])
    return err / ref if ref else None


def check_consistency(
    rec: Mapping[str, list[dict[str, Any]]],
    val_units: Mapping[str, list[dict[str, Any]]],
    pairs: Mapping[str, list[dict[str, Any]]],
    pages: Mapping[str, list[dict[str, Any]]],
    results: Mapping[str, Any],
) -> dict[str, Any]:
    """Plan items 4 and 5, "consistency first"; any difference stops the run."""
    problems: list[str] = []
    checked = 0
    for s, rows in rec.items():
        entry = p14_entry(results, "GW-REC-039", "rec", s)
        for t in ps.rec_tracks(s):
            _agree(
                f"GW-REC-039 {s} {t} CER",
                _line_cer(rows, t),
                _value(entry["tracks"][t]["cer"]),
                problems,
            )
            checked += 1
    val = p14_entry(results, "GW-REC-038", "rec", VAL_SET)
    for t in TRACKS:
        _agree(
            f"GW-REC-038 {t} CER",
            _line_cer(val_units[t], t),
            _value(val["tracks"][t]["cer"]),
            problems,
        )
        checked += 1
    cond_rows = [
        r
        for r in (results.get("gdc_conditions") or {}).get("rows", [])
        if (r.get("experiment"), r.get("system"), r.get("task")) == ("GW-REC-039", GLYPHARIS, "rec")
    ]
    if not cond_rows:
        problems.append("results.json has no gdc_conditions rows for GW-REC-039")
    for r in cond_rows:
        sel = [x for x in rec["gdc_test"] if x.get("condition") == r["condition"]]
        for t in TRACKS:
            _agree(
                f"GW-REC-039 gdc_test {r['condition']} {t} CER",
                _line_cer(sel, t),
                _value(r["tracks"][t]["cer"]),
                problems,
            )
            checked += 1
    pages_checked = 0
    for s in PAGE_SETS:
        by_page = {r["key"]: r["systems"] for r in pages[s]}
        keys = [r["key"] for r in pairs[s]]
        if len(set(keys)) != len(keys) or set(keys) != set(by_page):
            problems.append(f"{s}: e2e_pairs and pages_ cover different pages")
            continue
        for r in pairs[s]:
            sysv = by_page[r["key"]]
            if PIPELINE not in sysv:
                problems.append(f"{s} {r['key']}: pages_ has no {PIPELINE}")
                continue
            for t in TRACKS:
                v = sysv[PIPELINE][t]
                ref = sum(int(p[t]["ref_chars"]) for p in r["pairs"])
                missed = sum(int(p[t]["ref_chars"]) for p in r["pairs"] if p["pred"] is None)
                matched = sum(int(p[t]["char_errors"]) for p in r["pairs"] if p["pred"] is not None)
                if ref != int(v["bag_ref_chars"]):
                    problems.append(f"{s} {r['key']} {t}: bag reference characters differ")
                if missed + matched > int(v["bag_errors"]):
                    problems.append(f"{s} {r['key']} {t}: missed + matched > bag errors")
            pages_checked += 1
        for exp, task, name in (("GW-E2E-007", "e2e", PIPELINE), ("GW-E2E-008", "oracle", ORACLE)):
            if task == "oracle" and s not in ORACLE_SETS:
                continue
            entry = p14_entry(results, exp, task, s)
            for t in TRACKS:
                for metric, num, den in (
                    ("page_cer_bag_of_lines", "bag_errors", "bag_ref_chars"),
                    ("page_cer_order_aware", "aware_errors", "aware_ref_chars"),
                ):
                    want = _value(entry["tracks"][t].get(metric))
                    if want is None:
                        continue  # not reported for this set (n/a)
                    vals = [by_page[k][name][t] for k in by_page if name in by_page[k]]
                    d = sum(int(x[den]) for x in vals)
                    got = sum(int(x[num]) for x in vals) / d if d else None
                    _agree(f"{exp} {s} {t} {metric}", got, want, problems)
                    checked += 1
    if problems:
        raise SystemExit(
            "the hand-off does not reproduce Phase 14's numbers; nothing is written:\n  "
            + "\n  ".join(problems[:20])
        )
    return {"values_checked": checked, "pages_checked": pages_checked, "result": "equal"}


