def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8", newline="\n")


def _protected_roots(data: Path) -> list[Path]:
    """The data roots whose `errors.PROTECTED_OUTPUTS` are never written: this run's and the
    repository's own."""
    roots = [data.resolve()]
    with contextlib.suppress(RuntimeError):  # not in a git repository: this run's root only
        roots.append((repo_root() / "data").resolve())
    return roots


OUTPUT_MARKER = ".phase15-output"  # in every folder this script writes; only those are replaced


def _within(path: Path, folder: Path) -> bool:
    """Whether ``path`` is ``folder`` or lies under it (both resolved)."""
    return path == folder or folder in path.parents


def check_output_paths(opts: Options) -> None:
    """Refuse output folders that could overwrite anything Phase 15 must not touch; runs before
    anything is read, and again before writing.

    An output folder is replaced whole, so it may not lie under a protected folder, may not hold
    the data root, a protected folder, the Phase 14 results or the repository, may not nest in
    another output, and, if it already exists, must be one this script wrote. The work folder,
    where the GDC crops are staged, must be git-ignored as a whole."""
    outs = {
        "--out": opts.out.resolve(),
        "--confusion-out": opts.confusion_out.resolve(),
        "the gallery folder": (opts.work / "galleries").resolve(),
    }
    roots = _protected_roots(opts.data)
    keep = [opts.data.resolve(), opts.results.resolve()]
    for root in roots:
        keep += [root, *(root.joinpath(*rel.split("/")) for rel in er.PROTECTED_OUTPUTS)]
    with contextlib.suppress(RuntimeError):
        keep.append(repo_root().resolve())
    for name, path in outs.items():
        for root in roots:
            hit = er.protected_folder(path, root)
            if hit is not None:
                raise SystemExit(
                    f"{name} {ps.shown(path)} is under data/{hit}, which Phase 15 never writes; "
                    "nothing is read or written"
                )
        for kept in keep:
            if _within(kept, path):
                raise SystemExit(
                    f"{name} {ps.shown(path)} holds {ps.shown(kept)}, which an output folder must "
                    "not replace; nothing is read or written"
                )
    items = list(outs.items())
    for i, (n1, p1) in enumerate(items):
        for n2, p2 in items[i + 1 :]:
            if _within(p1, p2) or _within(p2, p1):
                raise SystemExit(f"{n1} and {n2} overlap; nothing is read or written")
    for name, path in outs.items():
        if path.is_dir() and any(path.iterdir()) and not (path / OUTPUT_MARKER).is_file():
            raise SystemExit(
                f"{name} {ps.shown(path)} exists and was not written by this script; nothing is "
                "read or written"
            )
    work = opts.work.resolve()
    # Probe paths inside the work folder (it need not exist yet): the gallery itself and the
    # names its staging and parked copies take.
    probes = [work / "galleries", work / ".galleries.tmp-0", work / ".galleries.old-0"]
    if not all(git_ignored(x) for x in probes):
        raise SystemExit(
            f"{ps.shown(opts.work)} is not git-ignored; the gallery (GDC capture crops) and its "
            "staging folders must stay out of git, so nothing is read or written"
        )


def git_ignored(path: Path) -> bool:
    """Whether git ignores ``path`` (which need not exist): `git check-ignore -q`, run from the
    nearest existing folder; a path in no repository counts as not ignored."""
    anchor = path
    while not anchor.exists() and anchor.parent != anchor:
        anchor = anchor.parent
    if not anchor.is_dir():
        anchor = anchor.parent
    try:
        done = subprocess.run(
            ["git", "check-ignore", "-q", "--", path.as_posix()],
            cwd=anchor,
            capture_output=True,
            check=False,
        )
    except OSError:
        return False
    return done.returncode == 0


def copy_galleries(
    data: Path, folder: Path, draws: Sequence[Draw]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """The drawn crops into ``folder`` (the gallery, git-ignored), each hashed again just before
    it is copied; returns the gallery index and one read record per crop. A line of a
    `NO_QUOTE` source carries no text in the index either."""
    crops = data / HANDOFF / "gdc_crops"
    rows, record = [], []
    for i, d in enumerate(draws):
        src = crops / d.file
        sha = sha256_file(src) if src.is_file() else None
        if sha != d.sha256:
            raise SystemExit(f"the crop {d.file} changed since it was checked; nothing is written")
        record.append(
            {
                "file": ps.data_rel(src, data),
                "sha256": sha,
                "lines": None,
                "check": "gdc_crops/index.jsonl, again before copying it into the gallery",
                "checked_utc": _now(),
                "crop": True,
            }
        )
        dest = folder / d.group / f"{i:03d}_{PurePosixPath(d.file).name}"
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dest)
        row: dict[str, Any] = {
            "group": d.group,
            "key": d.key,
            "file": dest.relative_to(folder).as_posix(),
            "sha256": d.sha256,
            "quoted": d.quoted,
        }
        if d.quoted:
            row["ref"], row["pred"] = d.ref, d.pred
        rows.append(row)
    _write(folder / "index.json", json.dumps(rows, indent=1, ensure_ascii=False))
    return rows, record


def _hier_json(s: str, doc: dict[str, Any]) -> dict[str, Any]:
    """A confusion-table document, with the HierText attribution when it is HierText's."""
    if s in HIERTEXT_SETS:
        return {"licence": {"attribution": HIERTEXT_ATTRIBUTION, "note": SHARE_ALIKE_NOTE}, **doc}
    return doc


def _staging(final: Path) -> Path:
    """A temporary sibling of ``final`` (same folder, so the rename stays on one drive)."""
    return final.parent / f".{final.name}.tmp-{os.getpid()}"


def _missing_ancestors(paths: Iterable[Path]) -> list[Path]:
    """The folders above ``paths`` that do not exist yet, deepest first."""
    out: set[Path] = set()
    for p in paths:
        d = p.parent
        while not d.exists() and d.parent != d:
            out.add(d)
            d = d.parent
    return sorted(out, key=lambda d: len(d.parts), reverse=True)


def write_outputs(opts: Options, res: dict[str, Any], draws: Sequence[Draw]) -> None:
    """Every output, written into temporary sibling folders and renamed into place only once
    all of them are complete. A failure removes the temporary folders (and any folder made for
    them) and leaves the previous outputs, if any, as they were."""
    check_output_paths(opts)
    gallery = opts.work / "galleries"
    finals = (opts.out, opts.confusion_out, gallery)
    stage = {f: _staging(f) for f in finals}
    made = _missing_ancestors(finals)
    old = {f: f.parent / f".{f.name}.old-{os.getpid()}" for f in finals}
    moved: list[Path] = []  # finals whose previous version is parked under old[f]
    placed: list[Path] = []  # finals now holding the new version
    try:
        for tmp in stage.values():
            if tmp.exists():
                shutil.rmtree(tmp)
            tmp.mkdir(parents=True)
            (tmp / OUTPUT_MARKER).write_text("written by scripts/phase15_errors.py", "utf-8")
        # The drawn crops first: re-hashed and copied before any report is written.
        index, copied = copy_galleries(opts.data, stage[gallery], draws)
        res["inputs"] = [*res["inputs"], *copied]
        res["galleries"] = {"folder": _shown(gallery, opts.data), "crops": len(index)}
        write_reports(opts, res, stage[opts.out], stage[opts.confusion_out])
        try:
            for f in finals:
                if f.exists():
                    f.rename(old[f])
                    moved.append(f)
            for f in finals:
                stage[f].rename(f)
                placed.append(f)
        except OSError:
            for f in placed:  # put the previous outputs back
                shutil.rmtree(f, ignore_errors=True)
            for f in moved:
                old[f].rename(f)
            raise
        for f in moved:
            shutil.rmtree(old[f], ignore_errors=True)
    finally:
        for tmp in stage.values():
            if tmp.exists():
                shutil.rmtree(tmp, ignore_errors=True)
        for d in made:  # folders made only for the staging folders
            with contextlib.suppress(OSError):
                d.rmdir()  # only when empty


def write_reports(opts: Options, res: dict[str, Any], out: Path, conf: Path) -> None:
    """The Markdown, PNG and JSON files into ``out`` and ``conf`` (the staging folders). The
    README is rendered last, so it states the number of intervals the other files printed."""
    res["confusion_dir"] = _shown(opts.confusion_out, opts.data)
    _PRINTED.clear()
    texts = {
        "recognition.md": render_recognition(res),
        "pipeline.md": render_pipeline(res),
        "oracle_share.md": render_oracle(res),
        "examples.md": render_examples(res),
        "glyphsynth.md": render_glyphsynth(res),
    }
    res["intervals_printed"] = len(_PRINTED)
    texts["README.md"] = render_readme(res)
    for name, text in texts.items():
        _write(out / name, text)
    for s in ("gdc_test", "hiertext_test"):
        class_matrix_png(
            out / f"class_matrix_{s}.png",
            s,
            res["recognition"][s]["tracks"]["strict"]["characters"]["class_matrix"],
        )
    text_sets = {s: r for s, r in res["recognition"].items() if s not in er.NUMBERS_ONLY}
    text_sets[VAL_SET] = res["validation"]
    for s, r in text_sets.items():
        chars = {
            t: {k: b[k] for k in ("characters", "label_fragments") if k in b}
            for t, b in r["tracks"].items()
        }
        words = {t: b["words"] for t, b in r["tracks"].items()}
        head = {"experiment": REC_EXPERIMENT, "data": r["experiment"], "set": s}
        _write(
            conf / f"characters_{s}.json",
            json.dumps(_hier_json(s, {**head, "tracks": chars}), indent=1, ensure_ascii=False),
        )
        _write(conf / f"characters_{s}.md", render_characters(s, r))
        _write(
            conf / f"words_{s}.json",
            json.dumps(_hier_json(s, {**head, "tracks": words}), indent=1, ensure_ascii=False),
        )
        _write(conf / f"words_{s}.md", render_words(s, r))
    _write(
        conf / "README.md",
        "\n".join(
            [
                NOTE,
                "",
                "# Character and word tables (GW-REC-040)",
                "",
                "One characters_<set> and words_<set> file per set with text (Markdown and "
                "JSON). GDC-scan is numbers only and has none; FUNSD and IIIT5K have no "
                "word pairs. Overview in `reports/error_cases/phase15/`.",
                "",
                SHARE_ALIKE,
                "",
            ]
        ),
    )
    _write(out / "results.json", json.dumps(res, indent=1, ensure_ascii=False))


def run(opts: Options) -> int:
    check_output_paths(opts)
    res, draws = analyse(opts)
    write_outputs(opts, res, draws)
    print(
        f"wrote {ps.shown(opts.out)}: {res['intervals_printed']} intervals printed, "
        f"{len(draws)} example crops"
    )
    return 0


