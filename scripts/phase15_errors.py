@dataclass
class Draw:
    """A drawn GDC crop: what the report lists and the gallery copies."""

    group: str
    key: str
    file: str
    sha256: str
    ref: str
    pred: str
    quoted: bool  # False for a `NO_QUOTE` source: its text is never written anywhere


def _draw(n: int, k: int, seed: Any) -> list[int]:
    if n == 0:
        return []
    return [
        int(i) for i in np.sort(np.random.default_rng(seed).choice(n, min(k, n), replace=False))
    ]


def gdc_examples(
    eval_set: str,
    units: Sequence[Mapping[str, Any]],
    index: Sequence[Mapping[str, Any]],
    ctx: Ctx,
) -> tuple[dict[str, Any], list[Draw]]:
    """The draws of plan item 4: the 20 most frequent strict-track edit-operation types (any
    kind, ranked by count, then operation and characters) with up to 3 crops each, type k
    (counted from 1) drawn with seed [20261115, k]; 40 error crops and 20 of the 200 correct
    crops (seed 20261115). Only lines with a crop in the hand-off are drawn. A line of a
    `NO_QUOTE` source is listed by id and numbers only."""
    er.refuse_numbers_only(eval_set, "an example list")
    crop = {str(r["key"]): r for r in index}
    by_key = {str(u["key"]): u for u in units}
    types: Counter[tuple[str, str, str]] = Counter()
    holders: dict[tuple[str, str, str], set[str]] = {}
    for u in units:
        for ty in er.edit_ops(u["ref_norm"], u["pred_norm"]):
            types[ty] += 1
            holders.setdefault(ty, set()).add(str(u["key"]))
    top = sorted(types.items(), key=lambda kv: (-kv[1], kv[0]))[:CONFUSION_TYPES]
    draws: list[Draw] = []

    def take(group: str, key: str) -> dict[str, Any]:
        c = crop[key]
        u = by_key.get(key)
        if u is None:
            raise SystemExit(f"the drawn GDC crop {key} has no line in rec_lines_{eval_set}")
        quoted = str(u["source"]) not in ctx.no_quote
        d = Draw(
            group, key, str(c["file"]), str(c["sha256"]), str(c["ref"]), str(c["pred"]), quoted
        )
        draws.append(d)
        row: dict[str, Any] = {
            "key": key,
            "source": u["source"],
            "char_errors": u["char_errors"],
            "ref_chars": u["ref_chars"],
            "crop": d.file,
            "quoted": quoted,
        }
        if quoted:
            row["ref"], row["pred"] = d.ref, d.pred
        return row

    out: dict[str, Any] = {"types": [], "errors": [], "correct": []}
    for k, ((op, r, p), n) in enumerate(top, start=1):
        keys = sorted(x for x in holders[(op, r, p)] if x in crop)
        picks = _draw(len(keys), PER_TYPE, [EXAMPLE_SEED, k])
        out["types"].append(
            {
                "rank": k,
                "seed": [EXAMPLE_SEED, k],
                "op": op,
                "ref": r,
                "pred": p,
                "count": n,
                "lines_holding": len(holders[(op, r, p)]),
                "with_crop": len(keys),
                "drawn": [take(f"type{k:02d}", keys[i]) for i in picks],
            }
        )
    errs = sorted(str(r["key"]) for r in index if r["kind"] == "error")
    right = sorted(str(r["key"]) for r in index if r["kind"] == "correct")
    out["errors"] = [take("errors", errs[i]) for i in _draw(len(errs), ERROR_DRAW, EXAMPLE_SEED)]
    out["correct"] = [
        take("correct", right[i]) for i in _draw(len(right), CORRECT_DRAW, EXAMPLE_SEED)
    ]
    out["error_crops"], out["correct_crops"] = len(errs), len(right)
    return out, draws


def worst_pages(
    eval_set: str, pages_rows: Sequence[Mapping[str, Any]], pairs_rows: Sequence[Mapping[str, Any]]
) -> list[dict[str, Any]]:
    """The 10 worst pages of the pipeline (strict bag errors descending, key ascending)."""
    cond = {r["key"]: r.get("condition") for r in pairs_rows}
    vals = [(r["key"], r["systems"][PIPELINE]["strict"]) for r in pages_rows]
    vals.sort(key=lambda kv: (-int(kv[1]["bag_errors"]), str(kv[0])))
    out = []
    for k, v in vals[:WORST_PAGES]:
        e, r = int(v["bag_errors"]), int(v["bag_ref_chars"])
        row: dict[str, Any] = {"bag_errors": e, "bag_ref_chars": r, "cer": e / r if r else None}
        if eval_set not in er.NUMBERS_ONLY:
            row["key"] = k
        if eval_set == "gdc_test":
            row["condition"] = cond.get(k)
        out.append(row)
    return out


