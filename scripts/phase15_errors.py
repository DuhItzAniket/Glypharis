# The intervals as the renderers print them: each stored interval (one dict of the results) is
# counted once, however often it is shown; `write_outputs` clears it before rendering.
_PRINTED: set[int] = set()


def md(s: Any) -> str:
    """Text as a Markdown table cell."""
    t = str(s).replace("\\", "\\\\").replace("|", "\\|").replace("`", "\\`")
    t = t.replace("*", "\\*").replace("_", "\\_").replace("<", "&lt;")
    return " ".join(t.splitlines())


def show(ch: str) -> str:
    if ch == "":
        return "∅"
    if ch == " ":
        return "␠ (space)"
    return f"{md(ch)} (U+{ord(ch[0]):04X})"


def pct(d: Mapping[str, Any] | None) -> str:
    """A rate with its interval, in per cent; counts the interval as printed."""
    if not d:
        return "n/a"
    _PRINTED.add(id(d))
    return f"{100 * d['value']:.2f} [{100 * d['low']:.2f}, {100 * d['high']:.2f}]"


def _plain(d: Mapping[str, Any] | None, value: float | None = None) -> str:
    """A mean with its interval (or ``value`` alone without one); counts the interval."""
    if not d:
        return "n/a" if value is None else f"{value:.3f}"
    _PRINTED.add(id(d))
    return f"{d['value']:.3f} [{d['low']:.3f}, {d['high']:.3f}]"


def p100(x: float | None, digits: int = 2) -> str:
    return "n/a" if x is None else f"{100 * x:.{digits}f}"


def table(head: list[str], rows: list[list[str]]) -> list[str]:
    return ps.table(head, rows)


def _cited(row: Mapping[str, Any]) -> Mapping[str, Any] | None:
    cited: Mapping[str, Any] | None = (
        row.get("ci_clusters") or row.get("ci_pages") or row.get("ci_lines")
    )
    return cited


def _cer_cell(row: Mapping[str, Any], key: str = "cer") -> str:
    """A rate with the cited CI (clusters or pages when there, otherwise lines); the value alone
    below the minimum cell size or off the primary track."""
    cited = _cited(row)
    return pct(cited) if cited else f"{100 * row[key]:.2f}"


def _line_cell(row: Mapping[str, Any]) -> str:
    """The line CI beside a cited page or cluster CI ("cited" when it is the cited one)."""
    if not row.get("ci_lines"):
        return "n/a"
    if _cited(row) is row["ci_lines"]:
        return "cited"
    return pct(row["ci_lines"])


def share_cell(v: Mapping[str, Any], ci: str) -> str:
    """A share with its interval, or its value alone when the cell has none."""
    if v.get(ci):
        return pct(v[ci])
    return "-" if v.get("value") is None else f"{100 * v['value']:.2f}"


def slice_lines(
    title: str,
    rows: Sequence[Mapping[str, Any]],
    beside: Mapping[str, Sequence[Mapping[str, Any]]] | None = None,
    set_ceiling: str | None = None,
) -> list[str]:
    """One slice table: the primary track's rows, other tracks' CER beside them. Rows carry
    their own charset ceiling when their units have text; otherwise the set's (``set_ceiling``)
    is printed with the title."""
    beside = beside or {}
    other = {t: {str(r["label"]): r for r in rs} for t, rs in beside.items()}
    per_row = any(r.get("ceiling") is not None for r in rows)
    head = [
        "Bin",
        "Lines",
        "Pages",
        "Ref chars",
        "Errors",
        "CER % [cited CI]",
        "CER % [line CI]",
        "Share of the set's errors %",
        *(["Charset ceiling %"] if per_row else []),
        *(f"CER % {t}" for t in other),
    ]
    body = []
    for r in rows:
        lab = str(r["label"])
        body.append(
            [
                md(lab),
                f"{r['lines']:,}",
                "-" if r.get("pages") is None else str(r["pages"]),
                f"{r['ref_chars']:,}",
                f"{r['char_errors']:,}",
                _cer_cell(r),
                _line_cell(r),
                p100(r["share"]),
                *([p100(r.get("ceiling"))] if per_row else []),
                *(p100(other[t][lab]["cer"]) if lab in other[t] else "n/a" for t in other),
            ]
        )
    caption = f"**{title}**"
    if not per_row and set_ceiling is not None:
        caption += f" (charset ceiling of the set: {set_ceiling})"
    return [caption, "", *table(head, body)]


