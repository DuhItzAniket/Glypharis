def char_tables(
    eval_set: str, units: Sequence[Mapping[str, Any]], track: str, allowed: frozenset[str]
) -> dict[str, Any]:
    """Edit operations, the top confusions, the class matrix and space errors of one track; each
    line's operations are asserted equal to its stored char_errors."""
    conf = er.Confusions(eval_set)
    for u in units:
        try:
            conf.add(u["ref_norm"], u["pred_norm"], u["char_errors"])
        except ValueError as exc:
            raise SystemExit(f"{eval_set} {u['key']} ({track}): {exc}") from exc
    top: dict[str, list[dict[str, Any]]] = {}
    for kind in er.OPS:
        rows = []
        for r, p, n, rate in conf.top(kind, TOP):
            gone = None
            if track == "strict":
                gone = _norm_char(r) == _norm_char(p) if kind == "sub" else _norm_char(r or p) == ""
            rows.append({"ref": r, "pred": p, "count": n, "rate": rate, "gone_normalised": gone})
        top[kind] = rows
    return {"totals": conf.totals(), "top": top, "class_matrix": conf.class_matrix(allowed)}


def word_tables(eval_set: str, units: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    words = er.WordErrors(eval_set)
    for u in units:
        words.add(u["ref_norm"], u["pred_norm"])
    out: dict[str, Any] = {"totals": words.totals()}
    if eval_set in WORD_PAIR_SETS:
        out["top"] = [{"ref": r, "pred": p, "count": n} for r, p, n in words.top(TOP)]
    return out


def categories(eval_set: str, units: Sequence[Mapping[str, Any]], ctx: Ctx) -> dict[str, Any]:
    """One primary category per wrong line, by the plan's precedence; shares add up to 1. Most
    rules read text, so a numbers-only set is refused (amendment 11: no category table)."""
    er.refuse_numbers_only(eval_set, "a category table")
    edges = {k: _edges(ctx.edges, k) for k in ("line_height_px", "blur", "contrast")}
    wrong = [u for u in units if u["char_errors"] > 0]
    lines: Counter[str] = Counter()
    errs: Counter[str] = Counter()
    for u in wrong:
        attrs = {
            k: u.get(k)
            for k in (
                "oov",
                "rotation_deg",
                "line_height_px",
                "blur",
                "contrast",
                "digit",
                "punct",
                "long_word",
            )
        }
        c = er.primary_category(attrs, edges)
        lines[c] += 1
        errs[c] += u["char_errors"]
    n, e = len(wrong), sum(errs.values())
    rows: list[dict[str, Any]] = [
        {
            "category": c,
            "lines": lines[c],
            "share_lines": lines[c] / n if n else 0.0,
            "char_errors": errs[c],
            "share_errors": errs[c] / e if e else 0.0,
        }
        for c in er.CATEGORIES
    ]
    if sum(r["lines"] for r in rows) != n or sum(r["char_errors"] for r in rows) != e:
        raise SystemExit("the categories do not add up to the wrong lines")
    return {"wrong_lines": n, "char_errors": e, "rows": rows}


def length_buckets(units: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """ADR-0002's revisit trigger: character errors by reference length (BUCKETS)."""
    total = sum(u["char_errors"] for u in units)
    out = []
    for lo, hi in BUCKETS:
        sel = [u for u in units if u["length"] >= lo and (hi is None or u["length"] < hi)]
        e, r = sum(u["char_errors"] for u in sel), sum(u["ref_chars"] for u in sel)
        out.append(
            {
                "from": lo,
                "to": hi,
                "lines": len(sel),
                "char_errors": e,
                "ref_chars": r,
                "cer": e / r if r else 0.0,
                "share": e / total if total else 0.0,
            }
        )
    return out


def documents(units: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    by: dict[str, list[Mapping[str, Any]]] = {}
    for u in units:
        by.setdefault(str(u["source"]), []).append(u)
    out = []
    for doc in sorted(by):
        e = sum(u["char_errors"] for u in by[doc])
        r = sum(u["ref_chars"] for u in by[doc])
        out.append(
            {
                "document": doc,
                "lines": len(by[doc]),
                "char_errors": e,
                "ref_chars": r,
                "cer": e / r if r else 0.0,
            }
        )
    return out


def grouped_no_ci(
    units: Sequence[Mapping[str, Any]],
    field_name: str,
    page_of: Callable[..., Hashable] | None,
    total: float,
) -> list[dict[str, Any]]:
    """Rows by ``field_name`` with per-document CERs and no CI (2 to 9 documents a group);
    shares of ``total``, the whole set's character errors."""
    rows = slice_table(units, lambda u: u[field_name], page_of, ci=False, total=total)
    for row in rows:
        row["documents"] = documents([u for u in units if u[field_name] == row["label"]])
    return rows


def gdc_documents(units: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """GDC's document groups, the condition x group counts, groups inside scan_app and
    conditions inside paper (the only group in every condition); counts and CER only."""
    total = float(sum(u["char_errors"] for u in units))
    counts: dict[str, dict[str, dict[str, int]]] = {}
    pages: dict[tuple[str, str], set[Hashable]] = {}
    for u in units:
        c, g = str(u["condition"]), str(u["group"])
        cell = counts.setdefault(c, {}).setdefault(g, {"lines": 0, "pages": 0})
        cell["lines"] += 1
        pages.setdefault((c, g), set()).add(u["page"])
    for (c, g), ps_ in pages.items():
        counts[c][g]["pages"] = len(ps_)
    return {
        "groups": grouped_no_ci(units, "group", _page, total),
        "condition_by_group": counts,
        "groups_in_scan_app": grouped_no_ci(
            [u for u in units if u["condition"] == "scan_app"], "group", _page, total
        ),
        "conditions_in_paper": grouped_no_ci(
            [u for u in units if u["group"] == "paper"], "condition", _page, total
        ),
    }


def rec_slices(
    eval_set: str, units: Sequence[Mapping[str, Any]], ctx: Ctx, has_pages: bool, ci: bool
) -> dict[str, list[dict[str, Any]]]:
    """Every slice of plan item 4 the set's fields allow."""
    page_of = _page if has_pages else None
    out: dict[str, list[dict[str, Any]]] = {}
    for name in EDGE_FIELDS:
        if all(u[name] is None for u in units):
            continue  # e.g. IIIT5K has no line height
        edges = _edges(ctx.edges, name)
        out[name] = slice_table(
            units,
            by_bin(name, edges),
            page_of,
            er.bin_labels(edges),
            ci=ci,
        )
    rot_labels = er.bin_labels(er.ROTATION_BINS)
    if any(u["rotation_deg"] is not None for u in units):
        out["rotation"] = slice_table(
            units, lambda u: er.rotation_bin(u["rotation_deg"]), page_of, rot_labels, ci=ci
        )
        if eval_set == "gdc_test":
            kept = [u for u in units if u["condition"] != "rotated"]
            out["rotation_without_rotated_pages"] = slice_table(
                kept,
                lambda u: er.rotation_bin(u["rotation_deg"]),
                page_of,
                rot_labels,
                ci=ci,
                total=float(sum(u["char_errors"] for u in units)),
            )
    if eval_set not in er.NUMBERS_ONLY:
        for flag in ("digit", "punct", "upper", "long_word", "oov"):
            out[flag] = slice_table(units, by_flag(flag), page_of, ci=ci)
    if eval_set == "gdc_test":
        out["condition"] = slice_table(
            units, lambda u: u["condition"], page_of, cluster=lambda u: u["source"], ci=ci
        )
    return out


def label_fragments(
    eval_set: str, units: Sequence[Mapping[str, Any]], track: str, ctx: Ctx, full: dict[str, Any]
) -> dict[str, Any]:
    """HierText's likely label fragments, their share of insertions and of character errors, and
    the character tables without them (plan item 4, annotation noise)."""
    frag = [u for u in units if er.is_label_fragment(u["ref_norm"], u["pred_norm"])]
    rest = [u for u in units if not er.is_label_fragment(u["ref_norm"], u["pred_norm"])]
    part = char_tables(eval_set, frag, track, ctx.allowed[track])["totals"] if frag else None
    tot = full["totals"]
    return {
        "lines": len(frag),
        "char_errors": sum(u["char_errors"] for u in frag),
        "insertions": part["ins"] if part else 0,
        "share_of_insertions": (part["ins"] / tot["ins"]) if part and tot["ins"] else 0.0,
        "share_of_errors": (part["errors"] / tot["errors"]) if part and tot["errors"] else 0.0,
        "without": char_tables(eval_set, rest, track, ctx.allowed[track]),
    }


def worst_lines(
    eval_set: str, units: Sequence[Mapping[str, Any]], ctx: Ctx
) -> list[dict[str, Any]]:
    """The 20 worst lines (char_errors descending, key ascending); text only where allowed (a
    GDC line from a `NO_QUOTE` source is listed by id and numbers only)."""
    rows = sorted(units, key=lambda u: (-u["char_errors"], str(u["key"])))[:WORST_LINES]
    out = []
    for u in rows:
        row: dict[str, Any] = {"char_errors": u["char_errors"], "ref_chars": u["ref_chars"]}
        if eval_set not in er.NUMBERS_ONLY:
            row["key"] = u["key"]
        quoted = eval_set in WORD_PAIR_SETS
        if eval_set == "gdc_test":
            row["source"], row["condition"] = u["source"], u["condition"]
            quoted = quoted and str(u["source"]) not in ctx.no_quote
            row["quoted"] = quoted
        if quoted:
            row["ref"], row["pred"] = u["ref"], u["pred"]
        out.append(row)
    return out


def recognition(
    eval_set: str, rows: Sequence[Mapping[str, Any]], ctx: Ctx, *, validation: bool = False
) -> dict[str, Any]:
    """Every recognition table of one set (GW-REC-039's lines, or GW-REC-038's)."""
    tracks: tuple[RecTrack, ...] = TRACKS if validation else ps.rec_tracks(eval_set)
    primary = tracks[0]
    # Validation pages come from the line ids (`val_rows_as_lines`); IIIT5K has none.
    has_pages = validation or EVAL_SETS[eval_set]["pages"] is not None
    page_of = _page if has_pages else None
    text = eval_set not in er.NUMBERS_ONLY
    out: dict[str, Any] = {
        "experiment": "GW-REC-038" if validation else "GW-REC-039",
        "primary": primary,
        "lines": len(rows),
        "has_pages": has_pages,
        "tracks": {},
    }
    for t in tracks:
        ci = t == primary  # CIs on the primary track; the others carry values beside it
        units = line_units(eval_set, rows, t, ctx, has_pages)
        b: dict[str, Any] = {
            "empty_references": len(rows) - len(units),
            "ceiling": ctx.ceilings.get(eval_set, {}).get(t),
            "totals": slice_table(units, lambda u: "all", page_of, ci=ci),
            "slices": rec_slices(eval_set, units, ctx, has_pages, ci),
            "length_buckets": length_buckets(units),
        }
        if text:
            b["characters"] = char_tables(eval_set, units, t, ctx.allowed[t])
            b["words"] = word_tables(eval_set, units)
            b["categories"] = categories(eval_set, units, ctx)
            if eval_set in HIERTEXT_SETS:
                b["label_fragments"] = label_fragments(eval_set, units, t, ctx, b["characters"])
        if eval_set == "gdc_test":
            b["documents"] = gdc_documents(units)
        if t == primary:
            b["worst_lines"] = worst_lines(eval_set, units, ctx)
        out["tracks"][t] = b
    return out


def val_rows_as_lines(rows: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """GW-REC-038's records (ext_eval's rec fields) in the hand-off's per-line form, the page
    (``doc_id``) taken from the HierText line id ``<image>/p<i>/l<j>`` (amendment 11); a key
    of another form refuses."""
    out = []
    for r in rows:
        row = dict(r)
        try:
            row["doc_id"] = er.hiertext_page(str(r["key"]))
        except ValueError as exc:
            raise SystemExit(
                f"GW-REC-038: {exc}; the validation pages cannot be resampled"
            ) from exc
        for t in TRACKS:
            s = score_pair(str(r["pred"]), str(r["ref"]), t)
            row[t] = {"char_errors": s.char_errors, "ref_chars": s.ref_chars, "exact": s.exact}
        out.append(row)
    return out


def baseline_rates(
    eval_set: str,
    glyph_rows: Sequence[Mapping[str, Any]],
    files: Sequence[tuple[str, Path]],
    allowed: Mapping[str, frozenset[str]],
) -> list[dict[str, Any]]:
    """Substitution, insertion and deletion rates and class-matrix rates of GLYPHARIS and each
    baseline, every system with the GLYPHARIS charset classes (numbers only). Every baseline
    file must hold exactly the hand-off's lines (same keys, each once, same references), so the
    systems are rated on the same lines; anything else refuses."""
    er.refuse_numbers_only(eval_set, "a baseline confusion table")
    refs = {str(r["key"]): str(r["ref"]) for r in glyph_rows}
    if len(refs) != len(glyph_rows):
        raise SystemExit(f"rec_lines_{eval_set} holds a key twice")
    systems: list[tuple[str, str, list[tuple[str, str]]]] = [
        ("GW-REC-039", "GLYPHARIS v1", [(str(r["ref"]), str(r["pred"])) for r in glyph_rows])
    ]
    for exp, path in files:
        pairs = []
        seen: set[str] = set()
        for rec in read_jsonl(path):
            k = str(rec["key"])
            if k in seen:
                raise SystemExit(f"{exp} {eval_set}: the baseline file holds {k} twice")
            seen.add(k)
            if k in refs and refs[k] != rec["ref"]:
                raise SystemExit(
                    f"{exp} {eval_set}: the stored reference of {k} differs from the hand-off's"
                )
            pairs.append((str(rec["ref"]), str(rec["pred"])))
        if seen != set(refs):
            raise SystemExit(
                f"{exp} {eval_set}: the baseline file covers other lines than the hand-off "
                f"({len(seen - set(refs))} extra, {len(set(refs) - seen)} missing)"
            )
        systems.append((exp, SYSTEM_NAMES.get(SYSTEM_OF[exp], SYSTEM_OF[exp]), pairs))
    out = []
    for exp, name, pairs in systems:
        for t in TRACKS:
            conf = er.Confusions(eval_set)
            for ref, pred in pairs:
                rn = normalise(ref, t)
                if rn:
                    conf.add(rn, normalise(pred, t), score_pair(pred, ref, t).char_errors)
            tot = conf.totals()
            cm = conf.class_matrix(allowed[t])
            out.append(
                {
                    "experiment": exp,
                    "system": name,
                    "track": t,
                    "lines": tot["lines"],
                    "ref_chars": tot["ref_chars"],
                    "cer": tot["cer"],
                    "sub_rate": tot["sub_rate"],
                    "ins_rate": tot["ins_rate"],
                    "del_rate": tot["del_rate"],
                    "class_rates": cm["rates"],
                    "correct": cm["correct"],
                    "correct_rates": cm["correct_rates"],
                }
            )
    return out


