def _source_cells(key: str, res: Mapping[str, Any]) -> str:
    """A GDC line's document key, source URL and licence."""
    s = res["examples"]["sources"].get(key)
    if s is None:
        raise SystemExit(f"GDC source {key} has no licence record; nothing is written")
    return f"{md(key)}, {md(s['url'])}, {md(s['licence'])}"


def _unquoted(key: str, res: Mapping[str, Any]) -> str:
    licence = res["examples"]["sources"][key]["licence"]
    return f"not quoted ({md(licence)})"


def render_worst_lines(s: str, r: Mapping[str, Any], res: Mapping[str, Any]) -> list[str]:
    rows = r["tracks"][r["primary"]].get("worst_lines") or []
    out = [f"**The {WORST_LINES} worst lines of {s} ({r['primary']})**", "", *_hier_note(s)]
    if s in WORD_PAIR_SETS:
        head = ["Key", "Errors", "Ref chars", "Reference", "Prediction"]
        body = []
        for x in rows:
            if x.get("quoted", True):
                text = [md(x["ref"]), md(x["pred"])]
            else:
                text = [_unquoted(str(x["source"]), res), "-"]
            body.append([md(x["key"]), str(x["char_errors"]), str(x["ref_chars"]), *text])
        if s == "gdc_test":
            head.append("Source (document key, URL, licence)")
            for row, x in zip(body, rows, strict=True):
                row.append(_source_cells(str(x["source"]), res))
    elif s in er.NUMBERS_ONLY:
        head = ["Rank", "Errors", "Ref chars"]
        body = [
            [str(i + 1), str(x["char_errors"]), str(x["ref_chars"])] for i, x in enumerate(rows)
        ]
    else:
        head = ["Key", "Errors", "Ref chars"]
        body = [[md(x["key"]), str(x["char_errors"]), str(x["ref_chars"])] for x in rows]
    return out + table(head, body)


