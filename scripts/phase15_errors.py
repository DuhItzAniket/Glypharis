def page_sources(rec_rows: Sequence[Mapping[str, Any]]) -> dict[str, str]:
    """GDC page -> source document, from the hand-off's lines (one source per page, checked)."""
    out: dict[str, str] = {}
    for r in rec_rows:
        k, s = str(r["doc_id"]), str(r["source"])
        if out.setdefault(k, s) != s:
            raise SystemExit(f"GDC page {k} has lines from two source documents")
    return out


def budget(
    eval_set: str,
    pairs_rows: Sequence[Mapping[str, Any]],
    pages_rows: Sequence[Mapping[str, Any]],
    track: str,
) -> dict[str, dict[str, Any]]:
    """`errors.page_budget` on every page; a budget that does not hold stops the run."""
    bag = {r["key"]: r["systems"][PIPELINE][track]["bag_errors"] for r in pages_rows}
    out = {}
    for r in pairs_rows:
        try:
            out[str(r["key"])] = er.page_budget(r, int(bag[r["key"]]), track)
        except ValueError as exc:
            raise SystemExit(
                f"{eval_set}: the page error budget does not hold ({exc}); nothing is written"
            ) from exc
    return out


def budget_block(
    budgets: Mapping[str, Mapping[str, Any]],
    cluster_of: Mapping[str, Hashable] | None,
    ci: bool,
    page_ci: bool = True,
) -> dict[str, Any]:
    """The budget's sums over a set of pages, with the shares of bag errors; intervals only
    with ``ci`` (the strict track), the page one only with ``page_ci``."""
    keys = sorted(budgets)
    den = {k: float(budgets[k]["bag_errors"]) for k in keys}
    clusters = {k: cluster_of[k] for k in keys} if cluster_of is not None else None
    out: dict[str, Any] = {"pages": len(keys)}
    for part in ("bag_errors", "missed", "matched", "spurious"):
        out[part] = sum(int(budgets[k][part]) for k in keys)
    out["unmatched"] = {
        b: sum(int(budgets[k]["unmatched"][b]) for k in keys) for b in er.UNMATCHED_BINS
    }
    out["shares"] = {
        part: share({k: float(budgets[k][part]) for k in keys}, den, clusters, ci, page_ci)
        for part in ("missed", "matched", "spurious")
    }
    return out


def pipeline(
    eval_set: str,
    pairs_rows: Sequence[Mapping[str, Any]],
    pages_rows: Sequence[Mapping[str, Any]],
    rec_rows: Sequence[Mapping[str, Any]],
    ctx: Ctx,
) -> dict[str, Any]:
    """Plan item 5 on one line-level page set (numbers only: no text field is read)."""
    gdc = eval_set == "gdc_test"
    sources = page_sources(rec_rows) if gdc else None
    if sources is not None:
        lost = [str(r["key"]) for r in pairs_rows if str(r["key"]) not in sources]
        if lost:
            raise SystemExit(f"GDC pages without a source document: {lost[:3]}")
    cond = {str(r["key"]): str(r.get("condition")) for r in pairs_rows}
    out: dict[str, Any] = {
        "pages": len(pairs_rows),
        "ceiling": ctx.e2e_ceilings.get(eval_set, {}),
        "budget": {},
        "cropping": {},
    }
    for t in TRACKS:
        ci = t == "strict"  # intervals on the primary track only (amendment 11)
        b = budget(eval_set, pairs_rows, pages_rows, t)
        out["budget"][t] = budget_block(b, sources, ci)
        if gdc:
            # condition rows cite source-document intervals only
            out.setdefault("budget_by_condition", {})[t] = {
                c: budget_block({k: v for k, v in b.items() if cond[k] == c}, sources, ci, False)
                for c in sorted(set(cond.values()))
            }
        units = [
            {
                "char_errors": p[t]["char_errors"],
                "ref_chars": p[t]["ref_chars"],
                "page": r["key"],
                "iou": p["iou"],
            }
            for r in pairs_rows
            for p in r["pairs"]
            if p["pred"] is not None and int(p[t]["ref_chars"]) > 0
        ]
        out["cropping"][t] = slice_table(
            units,
            lambda u: er.bin_of(u["iou"], er.IOU_BINS),
            _page,
            er.bin_labels(er.IOU_BINS, low=0.5),
            ci=ci,
            total=float(out["budget"][t]["bag_errors"]),  # shares of the set's bag errors
        )
    lines = Counter(
        er.UNMATCHED_BINS[er.unmatched_bin(float(p["best_iou"]))]
        for r in pairs_rows
        for p in r["pairs"]
        if p["pred"] is None
    )
    out["unmatched_lines"] = {b: lines.get(b, 0) for b in er.UNMATCHED_BINS}
    out["detection"] = detection(eval_set, rec_rows, ctx)
    out["iou"] = iou_distribution(pairs_rows)
    if gdc:
        out["oracle_difference"] = oracle_difference(eval_set, pairs_rows, rec_rows)
        inv = [er.inversion_counts(r["pairs"]) for r in pairs_rows]
        inverted, consecutive = sum(a for a, _ in inv), sum(b for _, b in inv)
        out["inversions"] = {
            "inverted": inverted,
            "consecutive": consecutive,
            "value": inverted / consecutive if consecutive else None,
            "share": page_ci([a for a, _ in inv], [b for _, b in inv]),
        }
    return out


def detection(eval_set: str, rec_rows: Sequence[Mapping[str, Any]], ctx: Ctx) -> dict[str, Any]:
    """Recall at IoU 0.5 of the pack lines by line height and rotation (and GDC condition)."""
    units = [
        {
            "char_errors": int(bool(r["det_matched"])),
            "ref_chars": 1,
            "page": r["doc_id"],
            "line_height_px": r.get("line_height_px"),
            "rotation_deg": r.get("rotation_deg"),
            "condition": r.get("condition"),
            "source": r.get("source"),
        }
        for r in rec_rows
        if "det_matched" in r
    ]
    edges = _edges(ctx.edges, "line_height_px")

    def recall(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
        for row in rows:
            row["recall"], row["matched"] = row.pop("cer"), row.pop("char_errors")
            for k in ("share", "ref_chars"):
                row.pop(k, None)
        return rows

    out = {
        "lines": len(units),
        "all": recall(slice_table(units, lambda u: "all", _page)),
        "line_height_px": recall(
            slice_table(
                units, lambda u: er.bin_of(u["line_height_px"], edges), _page, er.bin_labels(edges)
            )
        ),
        "rotation": recall(
            slice_table(
                units,
                lambda u: er.rotation_bin(u["rotation_deg"]),
                _page,
                er.bin_labels(er.ROTATION_BINS),
            )
        ),
    }
    if eval_set == "gdc_test":
        out["rotation_without_rotated_pages"] = recall(
            slice_table(
                [u for u in units if u["condition"] != "rotated"],
                lambda u: er.rotation_bin(u["rotation_deg"]),
                _page,
                er.bin_labels(er.ROTATION_BINS),
            )
        )
        out["condition"] = recall(
            slice_table(units, lambda u: u["condition"], _page, cluster=lambda u: u["source"])
        )
    return out


def iou_distribution(pairs_rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Matched lines per IoU bin, and the share matched at 0.7 or more (page CI)."""
    labels = er.bin_labels(er.IOU_BINS, low=0.5)
    counts: Counter[int | None] = Counter()
    hi, n = [], []
    for r in pairs_rows:
        ious = [float(p["iou"]) for p in r["pairs"] if p["pred"] is not None]
        counts.update(er.bin_of(x, er.IOU_BINS) for x in ious)
        hi.append(sum(x >= 0.7 for x in ious))
        n.append(len(ious))
    return {
        "bins": {labels[i]: counts.get(i, 0) for i in range(len(labels))},
        "matched": int(sum(n)),
        "ge_0.7": {"value": sum(hi) / sum(n) if sum(n) else None, "ci_pages": page_ci(hi, n)},
    }


def oracle_difference(
    eval_set: str, pairs_rows: Sequence[Mapping[str, Any]], rec_rows: Sequence[Mapping[str, Any]]
) -> dict[str, Any]:
    """GDC: the matched line's end-to-end errors minus the oracle's on the same line (strict),
    signed, after asserting that the pack label equals the page line's text; lines with an
    empty strict reference are left out. The mean per line cites a page resample (per-page
    sums of the differences over per-page line counts)."""
    er.refuse_numbers_only(eval_set, "the oracle difference")
    rec = {str(r["key"]): r for r in rec_rows}
    diffs, absent, empty = [], 0, 0
    per_page: dict[str, list[int]] = {}
    for r in pairs_rows:
        for p in r["pairs"]:
            if p["pred"] is None:
                continue
            if int(p["strict"]["ref_chars"]) == 0:
                empty += 1
                continue
            line = rec.get(str(p["line_id"]))
            if line is None or "oracle_strict" not in line:
                absent += 1
                continue
            if line["ref"] != p["ref"]:
                raise SystemExit(
                    f"GDC line {p['line_id']}: the pack label differs from the page line's text"
                )
            diff = int(p["strict"]["char_errors"]) - int(line["oracle_strict"]["char_errors"])
            diffs.append(diff)
            per_page.setdefault(str(r["key"]), []).append(diff)
    d = np.asarray(diffs, dtype=np.float64)
    pages = sorted(per_page)
    mean = None
    if d.size >= MIN_LINES:
        mean = page_ci([sum(per_page[k]) for k in pages], [len(per_page[k]) for k in pages])
    return {
        "lines": len(diffs),
        "pages": len(pages),
        "not_in_pack": absent,
        "empty_references": empty,
        "sum": int(d.sum()),
        "negative": int((d < 0).sum()),
        "zero": int((d == 0).sum()),
        "positive": int((d > 0).sum()),
        "mean_value": float(d.mean()) if d.size else None,
        "mean": mean,
    }


def reading_order(pages_rows: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Per system: order-aware minus bag-of-lines errors per page (descriptive); the page
    interval on the strict track only."""
    names = sorted({n for r in pages_rows for n in r["systems"]})
    out: dict[str, Any] = {}
    for name in names:
        out[name] = {}
        for t in TRACKS:
            least = MIN_PAGES if t == "strict" else NO_CI
            vals = [r["systems"][name][t] for r in pages_rows if name in r["systems"]]
            aware = np.asarray([int(v["aware_errors"]) for v in vals], dtype=np.float64)
            bag = np.asarray([int(v["bag_errors"]) for v in vals], dtype=np.float64)
            aref = sum(int(v["aware_ref_chars"]) for v in vals)
            bref = sum(int(v["bag_ref_chars"]) for v in vals)
            diff = aware - bag
            out[name][t] = {
                "pages": len(vals),
                "aware_errors": int(aware.sum()),
                "bag_errors": int(bag.sum()),
                "difference": int(diff.sum()),
                "pages_above_zero": int((diff > 0).sum()),
                "mean_value": float(diff.mean()) if diff.size else None,
                "mean_per_page": mean_ci(diff, "pages", least),
                "aware_cer": aware.sum() / aref if aref else None,
                "bag_cer": bag.sum() / bref if bref else None,
            }
    return out


def top_edges(files: Sequence[tuple[str, Path]]) -> list[dict[str, Any]]:
    """F26: share of consecutive output lines whose top edge does not go up (polygons only)."""
    out = []
    for exp, path in files:
        counts = [er.top_edge_order([ln["polygon"] for ln in r["lines"]]) for r in read_jsonl(path)]
        num, den = [a for a, _ in counts], [b for _, b in counts]
        out.append(
            {
                "experiment": exp,
                "system": SYSTEM_NAMES.get(SYSTEM_OF[exp], exp),
                "pages": len(counts),
                "non_rising": sum(num),
                "consecutive": sum(den),
                "value": sum(num) / sum(den) if sum(den) else None,
                "share": page_ci(num, den),
            }
        )
    return out


def oracle_share(
    eval_set: str,
    pages_rows: Sequence[Mapping[str, Any]],
    pairs_rows: Sequence[Mapping[str, Any]],
    rec_rows: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    """H4 on the strict bag of lines: oracle errors / pipeline errors over sets of pages. On GDC
    the clean slice, the other five conditions and those without rotated must have the plan's
    page and document counts (`H4_SIZES`); other counts mean wrong condition labels and refuse."""
    orc, pipe = {}, {}
    for r in pages_rows:
        s = r["systems"]
        if ORACLE not in s or PIPELINE not in s:
            raise SystemExit(f"{eval_set} {r['key']}: pages_ lacks the pipeline or the oracle")
        if int(s[ORACLE]["strict"]["bag_ref_chars"]) != int(s[PIPELINE]["strict"]["bag_ref_chars"]):
            raise SystemExit(
                f"{eval_set} {r['key']}: the oracle and the pipeline differ in reference characters"
            )
        orc[str(r["key"])] = float(s[ORACLE]["strict"]["bag_errors"])
        pipe[str(r["key"])] = float(s[PIPELINE]["strict"]["bag_errors"])
    gdc = eval_set == "gdc_test"
    slices: dict[str, list[str]] = {"all pages": sorted(pipe)}
    clusters: dict[str, str] | None = None
    if gdc:
        clusters = page_sources(rec_rows)
        cond = {str(r["key"]): str(r["condition"]) for r in pairs_rows}
        for c in sorted(set(cond.values())):
            slices[c] = sorted(k for k in pipe if cond[k] == c)
        named = {
            "clean": "clean (" + " + ".join(CLEAN_SLICE) + ")",
            "the other five": "the other five",
            "the other five without rotated": "the other five without rotated",
        }
        slices[named["clean"]] = sorted(k for k in pipe if cond[k] in CLEAN_SLICE)
        slices[named["the other five"]] = sorted(k for k in pipe if cond[k] not in CLEAN_SLICE)
        slices[named["the other five without rotated"]] = sorted(
            k for k in pipe if cond[k] not in CLEAN_SLICE and cond[k] != "rotated"
        )
        for h4, (want_pages, want_docs) in H4_SIZES.items():
            keys = slices[named[h4]]
            got = (len(keys), len({clusters[k] for k in keys}))
            if got != (want_pages, want_docs):
                raise SystemExit(
                    f"H4's {h4} slice has {got[0]} pages from {got[1]} documents, not the plan's "
                    f"{want_pages} from {want_docs}; nothing is written"
                )
    out = {}
    for name, keys in slices.items():
        cl = {k: clusters[k] for k in keys} if clusters is not None else None
        out[name] = share({k: orc[k] for k in keys}, {k: pipe[k] for k in keys}, cl)
    return out


