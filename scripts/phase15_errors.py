def gdc_licence(file: str) -> str:
    """A GDC source's licence from its file's folder (gdc_sources.json's licence note): arXiv
    CC BY 4.0, US federal works and Project Gutenberg public domain, the two textbooks CC BY-SA
    3.0. Any other file refuses: a line with no known licence is never quoted."""
    folder = PurePosixPath(file).parts[0] if PurePosixPath(file).parts else ""
    if folder in FOLDER_LICENCES:
        return FOLDER_LICENCES[folder]
    if file in TEXTBOOK_FILES:
        return CC_BY_SA
    if folder == "books" and PurePosixPath(file).name.startswith("pg-"):
        return GUTENBERG
    raise SystemExit(f"GDC source file {file} has no known licence; nothing is written")


def gdc_source_info(data: Path) -> tuple[dict[str, str], dict[str, dict[str, Any]]]:
    """Document group per GDC source (selection.yaml) and each source's licence and URL (the URL
    from gdc_sources.json, matched by file path). A source is quoted unless it is CC BY-SA (the
    `NO_QUOTE` textbooks); the selection key is the document key the report names."""
    selection = yaml.safe_load((data / GDC_SELECTION).read_text(encoding="utf-8"))
    files = json.loads((data / GDC_SOURCES).read_text(encoding="utf-8"))["files"]
    by_path = {str(v["path"]): v for v in files.values()}
    groups, info = {}, {}
    for doc in selection["documents"]:
        key, group, file = str(doc["key"]), str(doc["group"]), str(doc["file"])
        groups[key] = group
        path = str(PurePosixPath("raw/gdc_sources") / file)
        if path not in by_path:
            raise SystemExit(f"GDC source {key} ({file}) is not in gdc_sources.json")
        licence = gdc_licence(file)
        if (key in NO_QUOTE) != (licence == CC_BY_SA):
            raise SystemExit(f"GDC source {key} ({file}): licence {licence} and NO_QUOTE disagree")
        info[key] = {
            "group": group,
            "licence": licence,
            "url": by_path[path].get("url"),
            "quoted": licence != CC_BY_SA,
        }
    return groups, info


def jsonable(x: Any, counter: list[int]) -> Any:
    """Intervals as dicts (counted), tuples as lists, numpy scalars as Python numbers."""
    if isinstance(x, Interval):
        counter[0] += 1
        return dataclasses.asdict(x)
    if isinstance(x, dict):
        return {str(k): jsonable(v, counter) for k, v in x.items()}
    if isinstance(x, list | tuple):
        return [jsonable(v, counter) for v in x]
    if isinstance(x, np.bool_):
        return bool(x)
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, np.floating):
        return float(x)
    return x


