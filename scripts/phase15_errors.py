def slice_table(
    units: Sequence[Mapping[str, Any]],
    key: Callable[[Mapping[str, Any]], Hashable | None],
    page_of: Callable[[Mapping[str, Any]], Hashable] | None = None,
    labels: Sequence[str] | None = None,
    cluster: Callable[[Mapping[str, Any]], Hashable] | None = None,
    ci: bool = True,
    total: float | None = None,
) -> list[dict[str, Any]]:
    """`errors.slice_rows` with display labels for binned keys and the charset ceiling (share of
    the slice's reference characters outside the charset) when the units carry it.

    ``total`` is the whole set's character errors, for units that are a subset of it. A row
    with a cluster interval cites it and carries no page interval (amendment 11)."""
    rows = er.slice_rows(
        units,
        key,
        page_of=page_of,
        cluster=cluster,
        min_lines=MIN_LINES if ci else NO_CI,
        min_pages=MIN_PAGES,
        total=total,
        page_ci=cluster is None,
    )
    keys = [key(u) for u in units]
    for row in rows:
        lab = row["label"]
        sel = [u for u, k in zip(units, keys, strict=True) if k == lab]
        if sel and "oov_chars" in sel[0]:
            oov = sum(int(u["oov_chars"]) for u in sel)
            row["ceiling"] = oov / row["ref_chars"] if row["ref_chars"] else 0.0
        if labels is not None and isinstance(lab, int) and not isinstance(lab, bool):
            row["bin"], row["label"] = lab, labels[lab]
    return rows


def share(
    num: Mapping[str, float],
    den: Mapping[str, float],
    clusters: Mapping[str, Hashable] | None,
    ci: bool = True,
    page_ci: bool = True,
) -> dict[str, Any]:
    """`errors.share_ci` without intervals below `MIN_PAGES` pages or when ``ci`` is false (a
    track other than the primary one); ``page_ci`` false leaves out the page interval of a cell
    that cites only the cluster one."""
    big = ci and len(den) >= MIN_PAGES
    return er.share_ci(num, den, clusters, page_ci=big and page_ci, cluster_ci=big)


def page_ci(num: Sequence[float], den: Sequence[float]) -> Interval | None:
    """`stats.ratio_ci` over pages, or None below `MIN_PAGES` pages."""
    if len(num) < MIN_PAGES:
        return None
    return stats.ratio_ci(np.asarray(num, float), np.asarray(den, float), "pages")


def mean_ci(values: np.ndarray, unit: str, least: int) -> Interval | None:
    """`stats.mean_ci`, or None below ``least`` units."""
    return stats.mean_ci(values, unit) if values.size >= least else None


def ceiling_of(units: Sequence[Mapping[str, Any]]) -> float | None:
    """Reference characters outside the charset over all reference characters."""
    if not units or "oov_chars" not in units[0]:
        return None
    ref = sum(int(u["ref_chars"]) for u in units)
    return sum(int(u["oov_chars"]) for u in units) / ref if ref else 0.0


def _yes(flag: Any) -> str:
    return "yes" if flag else "no"


def by_bin(name: str, edges: Sequence[float]) -> Callable[[Mapping[str, Any]], int | None]:
    """A slice key: the bin of ``name`` between ``edges``."""
    return lambda u: er.bin_of(u[name], edges)


def by_flag(name: str) -> Callable[[Mapping[str, Any]], str]:
    """A slice key: "yes" or "no" for a flag."""
    return lambda u: _yes(u[name])


def by_capture(steps: Sequence[str]) -> Callable[[Mapping[str, Any]], str]:
    """A slice key: whether a GlyphSynth line went through any of ``steps``."""
    return lambda u: _yes(set(steps) & u["capture"])


def _norm_char(ch: str) -> str:
    """A character as the normalised track writes it (inside a word, so a space stays)."""
    return normalise(f"x{ch}x", "normalised")[1:-1]


def content_flags(
    eval_set: str, ref: str, pred: str, track: RecTrack, allowed: frozenset[str]
) -> dict[str, Any]:
    """The content of one line (and its normalised pair); refuses a numbers-only set."""
    er.refuse_numbers_only(eval_set, "a content flag")
    strict = normalise(ref, "strict")
    rn = normalise(ref, track)
    return {
        "digit": er.has_digit(strict),
        "punct": er.has_punct(strict),
        "upper": er.all_upper(strict),
        "long_word": er.has_long_word(strict),
        "oov": er.has_oov(rn, allowed),
        "oov_chars": sum(c not in allowed for c in rn),
        "ref_norm": rn,
        "pred_norm": normalise(pred, track),
        "ref": ref,
        "pred": pred,
    }


def line_units(
    eval_set: str,
    rows: Sequence[Mapping[str, Any]],
    track: RecTrack,
    ctx: Ctx,
    has_pages: bool,
) -> list[dict[str, Any]]:
    """Per line on ``track`` (empty normalised references left out): numbers, slice attributes
    and, for a set with text, the content flags. ``length`` is the strict-normalised reference
    length on every track (the measure the validation edges are fixed on)."""
    text = eval_set not in er.NUMBERS_ONLY
    out = []
    for r in rows:
        t = r[track]
        if int(t["ref_chars"]) == 0:
            continue
        u: dict[str, Any] = {
            "key": r["key"],
            "page": r.get("doc_id") if has_pages else None,
            "char_errors": int(t["char_errors"]),
            "ref_chars": int(t["ref_chars"]),
            "exact": bool(t["exact"]),
            "line_height_px": r.get("line_height_px"),
            "blur": r.get("blur"),
            "contrast": r.get("contrast"),
            "confidence": r.get("conf_t"),
            "length": int(r["strict"]["ref_chars"]),
            "rotation_deg": r.get("rotation_deg"),
            "condition": r.get("condition"),
            "source": r.get("source"),
        }
        u["group"] = ctx.groups.get(str(u["source"])) if u["source"] is not None else None
        if text:
            u.update(
                content_flags(eval_set, str(r["ref"]), str(r["pred"]), track, ctx.allowed[track])
            )
        out.append(u)
    return out


def _page(u: Mapping[str, Any]) -> Hashable:
    return u["page"]


