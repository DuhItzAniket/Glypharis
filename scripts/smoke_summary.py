"""Summarise the Phase 23 training smoke runs (item 11: GW-REC-046, GW-DET-008).

    python scripts/smoke_summary.py --runs <clone>/runs \
        --out reports/training/smoke/phase23_smoke.json

For each run it reads ``<runs>/<ID>/<ID>.jsonl`` (the event log), ``metrics.jsonl`` and
``summary.json`` and records: the commit and dirty flag, the optimizer steps, every resume (from the
event log, with the step it resumed at), the logged training losses (count, first, last, all
finite), and the diagnostic flags. It writes the JSON and a Markdown table beside it, with no local
paths. Exit status 0 when every run started, resumed exactly once, ended at a larger step than it
resumed from, logged only finite losses and raised no flag.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any

RUNS = ("GW-REC-046", "GW-DET-008")
RESUMED = re.compile(r"resumed from \S+ at epoch (\d+), batch (\d+), step (\d+)")


def _jsonl(path: Path) -> list[dict[str, Any]]:
    return [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def summarise(run_dir: Path, run_id: str) -> dict[str, Any]:
    events = _jsonl(run_dir / f"{run_id}.jsonl")
    metrics = _jsonl(run_dir / "metrics.jsonl")
    summary = json.loads((run_dir / "summary.json").read_text(encoding="utf-8"))
    resumes = [int(m.group(3)) for e in events if (m := RESUMED.search(str(e.get("message", ""))))]
    losses = [float(r["loss"]) for r in metrics if isinstance(r.get("loss"), (int, float))]
    git = summary.get("git", {})
    doc = {
        "run": run_id,
        "task": summary.get("task", "rec" if run_id.startswith("GW-REC") else "det"),
        "commit": git.get("commit"),
        "dirty": git.get("dirty"),
        "steps": summary.get("steps"),
        "resumed_at_steps": resumes,
        "losses_logged": len(losses),
        "loss_first": losses[0] if losses else None,
        "loss_last": losses[-1] if losses else None,
        "losses_finite": bool(losses) and all(math.isfinite(x) for x in losses),
        "flags": summary.get("flags", []),
    }
    steps = doc["steps"] or 0
    doc["passed"] = (
        len(resumes) == 1
        and steps > resumes[0]
        and doc["losses_finite"]
        and not doc["flags"]
        and doc["dirty"] is False
    )
    return doc


def render(doc: dict[str, Any]) -> str:
    rows = [
        f"| {r['run']} | {r['task']} | `{str(r['commit'])[:7]}` | {r['steps']} | "
        f"{', '.join(str(s) for s in r['resumed_at_steps']) or 'none'} | {r['losses_logged']} | "
        f"{r['loss_first']:.4f} | {r['loss_last']:.4f} | {'yes' if r['losses_finite'] else 'no'} | "
        f"{len(r['flags'])} | {'passed' if r['passed'] else 'FAILED'} |"
        for r in doc["runs"]
    ]
    return "\n".join(
        [
            "# Phase 23: training smoke runs",
            "",
            f"{doc['note']}",
            "",
            "| Run | Task | Commit | Steps | Resumed at step | Losses logged | First loss | "
            "Last loss | All finite | Flags | Verdict |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
            *rows,
            "",
            "Each run was cut short by `train.max_steps`, which writes `last.pt`, and then resumed "
            "once from it to a larger `train.max_steps`. This shows the training pipeline runs "
            "from a clean clone; it says nothing about the accuracy of v1's training, which used "
            "the full budget.",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--runs", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    runs = [summarise(args.runs / run_id, run_id) for run_id in RUNS]
    doc = {
        "note": "Generated by scripts/smoke_summary.py from the runs' event logs, metrics and "
        "summaries; do not edit by hand. No local paths.",
        "runs": runs,
        "passed": all(r["passed"] for r in runs),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8", newline="\n")
    args.out.with_suffix(".md").write_text(render(doc), encoding="utf-8", newline="\n")
    print(f"{args.out.as_posix()}: {'passed' if doc['passed'] else 'FAILED'}")
    return 0 if doc["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
