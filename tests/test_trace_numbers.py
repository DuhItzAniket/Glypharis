def run(
    root: Path, body: str, trace: dict[str, object] | None = None, path: str = DOC
) -> tn.DocumentCheck:
    write(root, path, body)
    if trace is not None:
        write(root, dv.trace_file_path(path), json.dumps({"document": path, **trace}))
    return make_check(root, path)


def make_check(root: Path, path: str = DOC) -> tn.DocumentCheck:
    repo = dv.Repo(root)
    trace_file, problems = dv.load_trace_file(repo, path)
    assert not problems, problems
    text = (root / path).read_bytes().decode("utf-8")
    return tn.DocumentCheck(repo, path, text, trace_file, dv.render_derived([trace_file]))


def traces(root: Path, body: str, trace: dict[str, object] | None = None) -> dict[str, tn.Trace]:
    check = run(root, body, trace)
    assert not check.problems, check.problems
    return {t.token.raw: t for t in check.run()}


def one(root: Path, body: str, raw: str, trace: dict[str, object] | None = None) -> tn.Trace:
    return traces(root, body, trace)[raw]


def resolved(root: Path, body: str, raw: str) -> bool:
    return one(root, body, raw).resolved


