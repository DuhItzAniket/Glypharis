def test_fraction_list_fits_the_real_reports() -> None:
    root = Path(__file__).resolve().parents[1]
    index = nt.ReportIndex(root)
    for pattern, _extra in tn.FRACTION_JSON:
        if pattern == "reports/other/results.json":
            continue
        files = [p.relative_to(root).as_posix() for p in (root / "reports").rglob("*.json")]
        chosen = [f for f in files if fnmatch.fnmatchcase(f, pattern)]
        assert chosen, pattern
        values = [v for f in chosen for v in index.file(f).values if tn.stores_fraction(f, v.where)]
        assert values, pattern
        # An error rate can pass 1 on a page; nothing stored as a fraction comes near 100.
        assert all(abs(v.value) < 10 for v in values), pattern


