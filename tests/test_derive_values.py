def test_output_records_formula_inputs_and_hashes(root: Path) -> None:
    trace_file(root, [ratio_entry()])
    assert dv.main(["--root", str(root)]) == 0
    data = json.loads((root / dv.DERIVED_OUTPUT).read_text(encoding="utf-8"))
    entry = data["documents"]["research/paper/doc.md"]["line_ratio"]
    assert entry["formula"] == "a / b"
    assert entry["value"] == "28.1450698904"
    assert entry["finest_digit"] == "1e-2"
    assert entry["experiments"] == ["GW-REC-001"]
    assert entry["inputs"]["a"]["line"] == 9
    assert entry["inputs"]["a"]["value"] == "74,500"
    assert (
        entry["inputs"]["a"]["sha256"] == dv.Repo(root).index.file("reports/rec/report.md").sha256
    )


def test_output_is_lf_and_repeatable(root: Path) -> None:
    trace_file(root, [ratio_entry()])
    assert dv.main(["--root", str(root)]) == 0
    first = (root / dv.DERIVED_OUTPUT).read_bytes()
    assert b"\r" not in first
    assert dv.main(["--root", str(root)]) == 0
    assert (root / dv.DERIVED_OUTPUT).read_bytes() == first


