def test_check_current_stale_and_crlf(root: Path, capsys: pytest.CaptureFixture[str]) -> None:
    trace_file(root, [ratio_entry()])
    assert dv.main(["--root", str(root), "--check"]) == 1  # not written yet
    assert dv.main(["--root", str(root)]) == 0
    assert dv.main(["--root", str(root), "--check"]) == 0
    path = root / dv.DERIVED_OUTPUT
    text = path.read_bytes()
    path.write_bytes(text.replace(b"\n", b"\r\n"))
    assert dv.main(["--root", str(root), "--check"]) == 0
    path.write_bytes(text.replace(b"a / b", b"a * b"))
    assert dv.main(["--root", str(root), "--check"]) == 1
    assert "out of date" in capsys.readouterr().err


def test_nothing_is_written_on_failure(root: Path, capsys: pytest.CaptureFixture[str]) -> None:
    bad = ratio_entry()
    bad["formula"] = "a / c"
    trace_file(root, [bad])
    assert dv.main(["--root", str(root)]) == 1
    assert not (root / dv.OUTPUT_DIR).exists()
    assert "disagree" in capsys.readouterr().err


def test_check_writes_nothing(root: Path) -> None:
    trace_file(root, [ratio_entry()])
    dv.main(["--root", str(root), "--check"])
    assert not (root / dv.OUTPUT_DIR).exists()
