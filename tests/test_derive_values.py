def write(root: Path, path: str, text: str) -> None:
    full = root / path
    full.parent.mkdir(parents=True, exist_ok=True)
    full.write_bytes(text.encode("utf-8"))


@pytest.fixture
def root(tmp_path: Path) -> Path:
    write(tmp_path, "research/experiments.md", REGISTRY)
    write(tmp_path, "research/paper/doc.md", "# Doc\n")
    write(tmp_path, "reports/rec/report.md", REPORT)
    return tmp_path


def trace_file(root: Path, derived: list[object], **extra: object) -> None:
    body = {"document": "research/paper/doc.md", "derived": derived, **extra}
    write(root, "research/paper/trace/doc.json", json.dumps(body))


def rec_input(**fields: object) -> dict[str, object]:
    return {"id": "GW-REC-001", "source": "reports/rec/report.md#val", **fields}


def ratio_entry() -> dict[str, object]:
    return {
        "name": "line_ratio",
        "formula": "a / b",
        "inputs": {
            "a": rec_input(row="hiertext", header="Lines"),
            "b": rec_input(row="funsd", header="Lines"),
        },
    }


def load(root: Path) -> tuple[dv.TraceFile, list[dv.Problem]]:
    return dv.load_trace_file(dv.Repo(root), "research/paper/doc.md")


def only_problem(root: Path) -> str:
    _, problems = load(root)
    assert len(problems) == 1, problems
    return problems[0].message


