# Formulas


def quantity(name: str, text: str) -> dv.DerivedInput:
    token = nt.tokenize(text)[0]
    value = Fraction(token.value)
    return dv.DerivedInput(name, "GW-REC-001", "r.md", 1, text, value, token.exponent, "")


@pytest.mark.parametrize(
    ("formula", "inputs", "value", "exponent"),
    [
        ("a / b", {"a": "9,739.4", "b": "2,637.3"}, Fraction(97394, 26373), -4),
        ("a - b", {"a": "2,637.3", "b": "2,579.1"}, Fraction(582, 10), -1),
        ("a + b", {"a": "1.5", "b": "2.25"}, Fraction(375, 100), -1),
        ("a * 100", {"a": "0.128"}, Fraction(128, 10), -1),
        ("(a - b) / b * 100", {"a": "12.0", "b": "10.0"}, Fraction(20), 0),
        ("-a", {"a": "2.5"}, Fraction(-5, 2), -1),
        ("abs(a - b)", {"a": "1.0", "b": "3.5"}, Fraction(5, 2), -1),
        ("max(a, b)", {"a": "1.0", "b": "3.5"}, Fraction(7, 2), -1),
        ("min(a, b)", {"a": "1.0", "b": "3.5"}, Fraction(1), -1),
        ("a", {"a": "7.25"}, Fraction(29, 4), -2),
    ],
)
def test_formula_value_and_precision(
    formula: str, inputs: dict[str, str], value: Fraction, exponent: int
) -> None:
    read = [quantity(k, v) for k, v in inputs.items()]
    assert dv.evaluate_formula(formula, read) == (value, exponent)


@pytest.mark.parametrize(
    ("formula", "message"),
    [
        ("a / 0", "division by zero"),
        ("a ** 2", "unsupported"),
        ("a.real", "unsupported"),
        ("open(a)", "disagree"),
        ("a if a else a", "unsupported"),
        ("a +", "does not parse"),
        ("b", "disagree"),
        ("a + b", "disagree"),
    ],
)
def test_bad_formulas(formula: str, message: str) -> None:
    with pytest.raises(dv.TraceFileError, match=message):
        dv.evaluate_formula(formula, [quantity("a", "1.5")])


def test_a_formula_without_inputs_is_refused() -> None:
    with pytest.raises(dv.TraceFileError, match="uses no input"):
        dv.evaluate_formula("1 + 2", [])


