def test_input_by_value_alone(root: Path) -> None:
    entry = {"name": "x", "formula": "a / 1000", "inputs": {"a": rec_input(value="92.25")}}
    trace_file(root, [entry])
    trace, problems = load(root)
    assert not problems
    assert trace.derived[0].inputs[0].line == 12
    assert trace.derived[0].value == Fraction(9225, 100000)


def test_a_cell_with_several_numbers_needs_a_value(root: Path) -> None:
    fields = {"row": "hiertext", "header": "CER %"}
    trace_file(root, [{"name": "x", "formula": "a", "inputs": {"a": rec_input(**fields)}}])
    assert "add value" in only_problem(root)
    picked = rec_input(value="6.36", **fields)
    trace_file(root, [{"name": "x", "formula": "a", "inputs": {"a": picked}}])
    trace, problems = load(root)
    assert not problems and trace.derived[0].value == Fraction(636, 100)


