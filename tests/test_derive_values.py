def test_claimed_ids_and_how_they_are_known(root: Path) -> None:
    write(root, "reports/phase16/a.md", "Generated by `s.py` (GW-EFF-006 to 008); by hand no.\n")
    write(root, "reports/GW-EFF-007/b.md", "# No header\n")
